"""ABI judge for the VideoToolbox plug-in (WP10).

Mode 1 (default): generate a C file that prints sizeof/offsetof for every
member of the structures in include/n2vt_abi.h, compile it for the host
(LP64, the same layout as arm64) with -DN2_HOST_FAKE, run it, and compare
with abi_expect.json.  --headers DIR points at another copy of the headers
(used by the self-test to prove that a removed member is caught).

Mode 2: --dylib build/ios/Slim.videoencoder
  * llvm-nm -gU defines exactly _SLIMEncoderRegister and _n2vt_version;
  * every llvm-nm -u undefined symbol is exported by some sdk/lib/*.tbd;
  * the install name is /System/Library/VideoEncoders/Slim.videoencoder and
    the file contains an arm64 slice;
  * the binary contains no string "/home/".

Exit 0 with "ORACLE abi PASS ..."; exit 1 with "ORACLE abi FAIL: reason".
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
VIDEO = os.path.dirname(HERE)

STRUCTS = [
    # (C type, [members]) -- order matches abi_expect.json
    ("n2_CMBaseClass",
     ["version", "derivedStorageSize", "equal", "invalidate", "finalize",
      "copyDebugDescription", "copyProperty", "setProperty",
      "reserved8", "reserved9", "reserved10"]),
    ("n2_VTVideoEncoderClass",
     ["version", "startSession", "encodeFrame", "completeFrames",
      "copySupportedPropertyDictionary", "setProperties",
      "copySerializableProperties", "prepareToEncodeFrames", "reserved",
      "startTileSession", "prepareToEncodeTiles", "encodeTile",
      "completeTiles"]),
    ("n2_VTVideoEncoderVTable", ["reserved", "baseClass", "encoderClass"]),
    ("CMTime", ["value", "timescale", "flags", "epoch"]),
    ("CMSampleTimingInfo",
     ["duration", "presentationTimeStamp", "decodeTimeStamp"]),
]

EXPECTED_EXPORTS = {"_SLIMEncoderRegister", "_n2vt_version"}
PLUGIN_INSTALL_NAME = "/System/Library/VideoEncoders/Slim.videoencoder"


class Fail(Exception):
    pass


def write_probe(path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* SPDX-License-Identifier: MIT */\n")
        f.write("/* generated by check_abi.py -- prints the frozen header's layout */\n")
        f.write('#include "n2vt_abi.h"\n')
        f.write("#include <stdio.h>\n")
        f.write("#include <stddef.h>\n")
        f.write("int main(void)\n{\n")
        for typ, members in STRUCTS:
            f.write('  printf("SIZE %s %%zu\\n", sizeof(%s));\n' % (typ, typ))
            for m in members:
                f.write('  printf("OFF %s %s %%zu\\n", offsetof(%s, %s));\n'
                        % (typ, m, typ, m))
        f.write("  return 0;\n}\n")


def compile_and_run(headers, cc, workdir):
    src = os.path.join(workdir, "abi_probe.c")
    exe = os.path.join(workdir, "abi_probe")
    write_probe(src)
    cmd = [cc, "-std=c11", "-O0", "-g", "-Wall", "-Wextra", "-Werror",
           "-DN2_HOST_FAKE", "-I", headers, src, "-o", exe]
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        err = r.stderr.decode("utf-8", "replace").strip().splitlines()
        raise Fail("headers in %s do not compile: %s"
                   % (headers, " | ".join(err[:4]) or "(no compiler output)"))
    r = subprocess.run([exe], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise Fail("layout probe crashed (exit %d)" % r.returncode)
    got = {}
    for line in r.stdout.decode("utf-8", "replace").splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[0] == "SIZE":
            got.setdefault(parts[1], {})["size"] = int(parts[2])
        elif len(parts) == 4 and parts[0] == "OFF":
            got.setdefault(parts[1], {}).setdefault("members", {})[parts[2]] = int(parts[3])
        else:
            raise Fail("layout probe printed an unexpected line %r" % line)
    return got


def compare(got, expect):
    errors = []
    for typ, want in expect["structs"].items():
        g = got.get(typ)
        if g is None:
            errors.append("structure %s missing from the probe" % typ)
            continue
        if g.get("size") != want["size"]:
            errors.append("%s: sizeof is 0x%x, expected 0x%x"
                          % (typ, g.get("size", -1), want["size"]))
        gm = g.get("members", {})
        for m, off in want["members"].items():
            if m not in gm:
                errors.append("%s.%s missing" % (typ, m))
            elif gm[m] != off:
                errors.append("%s.%s is at 0x%x, expected 0x%x"
                              % (typ, m, gm[m], off))
        for m in gm:
            if m not in want["members"]:
                errors.append("%s.%s is not in abi_expect.json" % (typ, m))
    for typ in got:
        if typ not in expect["structs"]:
            errors.append("unexpected structure %s in the probe" % typ)
    return errors


def check_headers(args):
    headers = os.path.abspath(args.headers or os.path.join(VIDEO, "include"))
    if not os.path.exists(os.path.join(headers, "n2vt_abi.h")):
        raise Fail("no n2vt_abi.h in %s" % headers)
    with open(os.path.join(HERE, "abi_expect.json"), "r", encoding="utf-8") as f:
        expect = json.load(f)
    workdir = tempfile.mkdtemp(prefix="n2abi-")
    try:
        got = compile_and_run(headers, args.cc, workdir)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    errors = compare(got, expect)
    if errors:
        raise Fail("; ".join(errors[:8]))
    n = sum(len(v["members"]) for v in expect["structs"].values())
    return "headers=%s structs=%d members=%d" % (headers, len(expect["structs"]), n)


def run_tool(cmd):
    try:
        r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    except FileNotFoundError:
        raise Fail("%s not found" % cmd[0])
    if r.returncode != 0:
        raise Fail("%s failed (exit %d): %s"
                   % (" ".join(cmd[:2]), r.returncode,
                      r.stderr.decode("utf-8", "replace").strip()[:400]))
    return r.stdout.decode("utf-8", "replace")


def nm_symbols(dylib, nm, defined):
    args = [nm] + (["-gU"] if defined else ["-u"]) + [dylib]
    out = run_tool(args)
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if not parts:
            continue
        name = parts[-1]
        if name.startswith("_"):
            syms.append(name)
    return syms


def nm_undefined(dylib, nm):
    """(strong, weak) undefined _symbols, from llvm-nm -m -u."""
    out = run_tool([nm, "-m", "-u", dylib])
    strong, weak = set(), set()
    for line in out.splitlines():
        m = re.search(r"\(undefined\)\s+(weak\s+)?external\s+(\S+)", line)
        if not m:
            continue
        name = m.group(2)
        if not name.startswith("_"):
            continue
        (weak if m.group(1) else strong).add(name)
    return strong, weak


def tbd_symbols(sdk_lib):
    if not os.path.isdir(sdk_lib):
        return None
    syms = set()
    for name in os.listdir(sdk_lib):
        if not name.endswith(".tbd"):
            continue
        path = os.path.join(sdk_lib, name)
        try:
            text = open(path, "r", encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for m in re.finditer(r"(?<![\w$.])_[A-Za-z0-9_.$]+", text):
            syms.add(m.group(0))
    return syms


def check_dylib(args):
    dylib = os.path.abspath(args.dylib)
    if not os.path.exists(dylib):
        raise Fail("%s does not exist" % dylib)
    nm = args.nm or os.environ.get("LLVM_NM", "llvm-nm")
    objdump = args.objdump or os.environ.get("LLVM_OBJDUMP", "llvm-objdump")

    defined = set(nm_symbols(dylib, nm, True))
    if defined != EXPECTED_EXPORTS:
        raise Fail("global defined symbols are %s, expected exactly %s"
                   % (sorted(defined) or "(none)", sorted(EXPECTED_EXPORTS)))

    undef = set(nm_symbols(dylib, nm, False))
    strong, weak = nm_undefined(dylib, nm)
    sdk_lib = args.sdk_lib or os.path.join(VIDEO, "sdk", "lib")
    have = tbd_symbols(sdk_lib)
    if have is None:
        raise Fail("no TBD directory %s to check %d undefined symbol(s) against"
                   % (sdk_lib, len(undef)))
    # A strong undefined symbol must be covered by a TBD.  Weak imports are
    # allowed to be absent from the TBDs only when they are our own optional
    # encoder objects (the shim's weak_import n2avc_vt_create/n2jpeg_vt_create);
    # everything else (CoreFoundation, VideoToolbox, libSystem) must be listed.
    missing = sorted(s for s in strong if s not in have)
    if missing:
        raise Fail("strong undefined symbol(s) not in any sdk/lib/*.tbd: %s"
                   % ", ".join(missing[:12]))
    allowed_weak = {s for s in weak if s.startswith("_n2")}
    missing_weak = sorted(s for s in weak if s not in have and s not in allowed_weak)
    if missing_weak:
        raise Fail("weak undefined symbol(s) not in any sdk/lib/*.tbd: %s"
                   % ", ".join(missing_weak[:12]))

    ph = run_tool([objdump, "--macho", "--private-headers", dylib])
    ids = re.findall(r"name\s+(\S+)", ph)
    if PLUGIN_INSTALL_NAME not in ph:
        raise Fail("install name %s not found in LC_ID_DYLIB (saw %s)"
                   % (PLUGIN_INSTALL_NAME, ids[:4] or "no dylib name"))
    mach = re.search(r"MH_MAGIC_64\s+(\S+)", ph)
    if not mach:
        raise Fail("not a 64-bit Mach-O file")
    if mach.group(1).upper() != "ARM64":
        raise Fail("Mach-O CPU type is %s, expected ARM64" % mach.group(1))

    blob = open(dylib, "rb").read()
    for needle in (b"/home/", "/home/".encode("utf-16-le")):
        if needle in blob:
            raise Fail("the binary contains the host path string /home/")
    return ("dylib=%s exports=%d imports=%d (weak=%d allowed=%d) "
            "install_name=ok arm64=ok hostpaths=none"
            % (dylib, len(defined), len(strong) + len(weak), len(weak),
               len(allowed_weak)))


def main(argv):
    ap = argparse.ArgumentParser(description="ABI judge for the VideoToolbox plug-in (WP10)")
    ap.add_argument("--headers", help="directory containing n2vt_abi.h (default gpu/video/include)")
    ap.add_argument("--cc", default=os.environ.get("CC", "clang"))
    ap.add_argument("--dylib", help="check a built Slim.videoencoder instead of the headers")
    ap.add_argument("--sdk-lib", help="directory of *.tbd stubs (default gpu/video/sdk/lib)")
    ap.add_argument("--nm", help="llvm-nm (default: llvm-nm)")
    ap.add_argument("--objdump", help="llvm-objdump (default: llvm-objdump)")
    args = ap.parse_args(argv)
    try:
        if args.dylib:
            summary = check_dylib(args)
        else:
            summary = check_headers(args)
        print("ORACLE abi PASS " + summary)
        return 0
    except Fail as e:
        print("ORACLE abi FAIL: %s" % e)
        return 1
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as e:
        print("ORACLE abi FAIL: %s" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
