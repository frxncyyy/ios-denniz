"""Verify a regenerated WP09 manifest and every file it lists.

  verify_manifest.py --manifest COMMITTED --new REGENERATED --data DIR

The committed manifest must be byte-identical to the regenerated one (that is
the determinism check: no timestamps, no absolute paths, no tool-version drift
on this machine).  Then every raw sha256, every stream sha256, the decoded
frame count, ffmpeg's per-frame md5 and the first frame's luma md5 are checked
against the stored values.  Prints CHECKS <n>; exits 1 on the first mismatch.
"""

import argparse
import hashlib
import json
import os
import subprocess
import sys

CHECKS = 0


def ok():
    global CHECKS
    CHECKS += 1


def need(cond, what):
    if not cond:
        raise SystemExit("verify_manifest: FAIL: %s" % what)
    ok()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fp:
        for chunk in iter(lambda: fp.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def frame_size(w, h):
    return w * h + 2 * ((w + 1) // 2) * ((h + 1) // 2)


def decode_framemd5(path):
    proc = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-f", "framemd5",
                           "-pix_fmt", "yuv420p", "-"],
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr.decode("utf-8", "replace")[-4000:])
        return None, None
    hashes = []
    dims = None
    for line in proc.stdout.decode("ascii", "replace").splitlines():
        if line.startswith("#dimensions 0:"):
            dims = line.split(":", 1)[1].strip()
        elif line and not line.startswith("#"):
            fields = [f.strip() for f in line.split(",")]
            if len(fields) < 6:
                return None, None
            hashes.append(fields[-1])
    return hashes, dims


def decode_luma_md5(path, w):
    proc = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-frames:v", "1",
                           "-f", "rawvideo", "-pix_fmt", "yuv420p", "-"],
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        return None
    raw = proc.stdout
    if len(raw) == 0 or len(raw) % w != 0:
        return None
    h = len(raw) * 2 // (3 * w)
    if len(raw) != frame_size(w, h):
        return None
    return hashlib.md5(raw[:w * h]).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--new", required=True)
    ap.add_argument("--data", required=True)
    args = ap.parse_args()

    old_bytes = open(args.manifest, "rb").read()
    new_bytes = open(args.new, "rb").read()
    need(old_bytes == new_bytes,
         "regenerated manifest is byte-identical to %s" % args.manifest)
    manifest = json.loads(old_bytes.decode("utf-8"))
    need(manifest.get("version") == 1, "manifest version 1")
    need(manifest.get("paths_relative_to") == "vectors/data",
         "paths are relative to vectors/data")
    need(manifest.get("mode") == "quick", "manifest was generated by 'quick'")

    names = set()
    for r in manifest["raw"]:
        need(r["name"] not in names, "raw name %s is unique" % r["name"])
        names.add(r["name"])
        path = os.path.join(args.data, r["path"])
        need(os.path.isfile(path), "raw file %s exists" % r["path"])
        size = os.path.getsize(path)
        need(size == r["frames"] * frame_size(r["width"], r["height"]),
             "%s has the expected size" % r["name"])
        need(sha256_file(path) == r["sha256"], "%s sha256" % r["name"])

    source = manifest["stream_sources"][0]
    src_path = os.path.join(args.data, source["path"])
    need(os.path.isfile(src_path), "stream source exists")
    need(sha256_file(src_path) == source["sha256"], "stream source sha256")

    for s in manifest["streams"]:
        path = os.path.join(args.data, s["path"])
        need(os.path.isfile(path), "stream %s exists" % s["name"])
        need(sha256_file(path) == s["sha256"], "%s sha256" % s["name"])
        hashes, dims = decode_framemd5(path)
        need(hashes is not None, "%s decodes with ffmpeg" % s["name"])
        need(len(hashes) == s["frames"],
             "%s decodes to %d frames" % (s["name"], s["frames"]))
        need(hashes == s["frame_md5"], "%s per-frame md5" % s["name"])
        if dims is not None:
            need(dims == "%dx%d" % (s["width"], s["height"]),
                 "%s decoded dimensions %dx%d" % (s["name"], s["width"], s["height"]))
        luma = decode_luma_md5(path, s["width"])
        need(luma is not None, "%s first frame decodes to YUV" % s["name"])
        need(luma == s["luma_md5_first_frame"], "%s luma md5 frame 0" % s["name"])

    print("CHECKS %d" % CHECKS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
