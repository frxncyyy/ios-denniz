"""Turn the llvm-mc object of guest_thumb.s into a C header with the code bytes and symbol offsets.

run_tests.sh calls this with the object and the .text-only binary:
    gen_blob.py guest_thumb.o guest_thumb.bin > /tmp/n2hw-v34/t_guest_blob.h

The header is included by t_support.c (bytes) and by the tests (T_OFF_<symbol>). The blob is placed at
T_DATA_ADDR in guest memory, so T_DATA_ADDR + T_OFF_main_args | 1 is the Thumb address of main_args.
"""
import re
import subprocess
import sys


def symbols(obj):
    out = subprocess.run(['llvm-nm', '--defined-only', obj], capture_output=True, text=True, check=True).stdout
    res = {}
    for line in out.splitlines():
        m = re.match(r'([0-9a-fA-F]+)\s+\S\s+(\S+)$', line.strip())
        if m:
            res[m.group(2)] = int(m.group(1), 16)
    return res


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: gen_blob.py <object> <binary>')
    obj, binary = sys.argv[1], sys.argv[2]
    code = open(binary, 'rb').read()
    syms = symbols(obj)
    if not code:
        sys.exit('gen_blob: empty .text')
    print('/* SPDX-License-Identifier: MIT */')
    print('/* generated by test_v34/gen_blob.py from guest_thumb.s -- do not edit */')
    print('#ifndef T_GUEST_BLOB_H')
    print('#define T_GUEST_BLOB_H')
    print('static const unsigned char t_guest_blob[%d] = {' % len(code))
    for i in range(0, len(code), 12):
        print('\t' + ', '.join('0x%02x' % b for b in code[i:i + 12]) + ',')
    print('};')
    for name in sorted(syms):
        print('#define T_OFF_%s 0x%04x' % (name, syms[name]))
    print('#endif')
    print('#define T_GUEST_BLOB_SIZE %d' % len(code))


if __name__ == '__main__':
    main()
