"""gen_enc.py -- turn v11_enc.s into a C header of encodings.

The encodings are produced by llvm-mc from assembly text; nothing here is typed
in by hand.  Usage:

    python3 gen_enc.py v11_enc.s out.h

Every instruction line in the source is preceded by a line "@ <name>"; the name
must be unique.  The output is

    #define ENC_<name> UINT32_C(0x........)

so a missing or renamed encoding is a compile error in t_v11.c.
"""
import re
import subprocess
import sys

LLVM_MC = ["llvm-mc",
           "-triple=armv7a-linux-gnueabi",
           "-mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8",
           "--show-encoding"]


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_enc.py <input.s> <output.h>\n")
        return 2
    src_path, out_path = sys.argv[1], sys.argv[2]

    with open(src_path, "r", encoding="utf-8") as f:
        lines = f.read().splitlines()

    # names[i] is the name for the i-th instruction line (comments/directives skipped)
    names = []
    pending = None
    n_insn = 0
    for line in lines:
        s = line.strip()
        if not s:
            continue
        if s.startswith("@"):
            pending = s[1:].strip()
            continue
        if s.startswith("."):
            continue
        n_insn += 1
        if not pending:
            sys.stderr.write("gen_enc.py: instruction without a name: %r\n" % s)
            return 2
        names.append(pending)
        pending = None

    proc = subprocess.run(LLVM_MC, stdin=open(src_path, "r", encoding="utf-8"),
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        return 1

    encs = []
    for line in proc.stdout.splitlines():
        m = re.search(r"encoding: \[([^\]]*)\]", line)
        if not m:
            continue
        bs = [int(x, 16) for x in m.group(1).split(",")]
        if len(bs) != 4:
            sys.stderr.write("gen_enc.py: unexpected encoding length: %r\n" % line)
            return 1
        encs.append(bs[0] | bs[1] << 8 | bs[2] << 16 | bs[3] << 24)

    if len(encs) != n_insn or len(names) != n_insn:
        sys.stderr.write("gen_enc.py: %d instructions, %d encodings, %d names\n"
                         % (n_insn, len(encs), len(names)))
        return 1

    seen = set()
    out = ["/* generated by gen_enc.py from %s -- do not edit */" % src_path,
           "#ifndef V11_ENC_H", "#define V11_ENC_H", ""]
    for name, word in zip(names, encs):
        if name in seen:
            sys.stderr.write("gen_enc.py: duplicate name %r\n" % name)
            return 1
        seen.add(name)
        if name.startswith("----"):
            continue
        out.append("#define ENC_%s UINT32_C(0x%08x)" % (name, word))
    out += ["", "#endif", ""]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    sys.stderr.write("gen_enc.py: %d encodings\n" % len(encs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
