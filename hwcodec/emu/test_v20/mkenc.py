# mkenc.py -- assemble the test corpus with llvm-mc and emit a C table of {name, 32-bit word}.
# Usage: mkenc.py out.h file.s [file2.s ...]
# Each input line is "name: instruction"; '#' starts a comment. No hand-written hex anywhere.
import re
import subprocess
import sys

TRIPLE = "armv8a-linux-gnueabi"
MATTR = "+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8,+crypto"


def parse(path):
    items = []
    for lineno, raw in enumerate(open(path), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if ':' not in line:
            sys.exit("%s:%d: expected 'name: instruction'" % (path, lineno))
        name, asm = line.split(':', 1)
        name, asm = name.strip(), asm.strip()
        if not name or not asm:
            sys.exit("%s:%d: empty name or instruction" % (path, lineno))
        items.append((name, asm, path, lineno))
    return items


def assemble(items):
    text = "\n".join(it[1] for it in items) + "\n"
    p = subprocess.run(
        ["llvm-mc", "-triple=" + TRIPLE, "-mattr=" + MATTR, "--show-encoding"],
        input=text.encode(), capture_output=True)
    if p.returncode != 0:
        sys.stderr.write(p.stderr.decode())
        sys.exit("llvm-mc failed")
    words = []
    for line in p.stdout.decode().splitlines():
        m = re.search(r"encoding: \[([0-9a-fx, ]+)\]", line)
        if not m:
            continue
        bs = [int(x, 16) for x in m.group(1).split(',')]
        if len(bs) != 4:
            sys.exit("unexpected encoding length in: " + line)
        words.append(bs[0] | bs[1] << 8 | bs[2] << 16 | bs[3] << 24)
    if len(words) != len(items):
        sys.stderr.write(p.stdout.decode())
        sys.stderr.write(p.stderr.decode())
        sys.exit("expected %d encodings, got %d" % (len(items), len(words)))
    return words


def main():
    out_path = sys.argv[1]
    items = []
    for path in sys.argv[2:]:
        items += parse(path)
    seen = set()
    for it in items:
        if it[0] in seen:
            sys.exit("duplicate encoding name %s" % it[0])
        seen.add(it[0])
    words = assemble(items)
    with open(out_path, "w") as f:
        f.write("/* generated by mkenc.py from %s -- do not edit */\n" %
                ", ".join(sys.argv[2:]))
        f.write("struct enc_ent { const char *name; uint32_t word; };\n")
        f.write("static const struct enc_ent enc_tab[] = {\n")
        for (name, asm, path, lineno), w in zip(items, words):
            f.write('\t{ "%s", 0x%08Xu }, /* %s */\n' % (name, w, asm))
        f.write("};\n")
        f.write("#define ENC_COUNT %d\n" % len(items))
    print("mkenc: %d encodings" % len(items))


if __name__ == "__main__":
    main()
