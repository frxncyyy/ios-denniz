#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
# gen_space.py -- sweep the three V20 encoding spaces with llvm-mc's disassembler and emit, for every word
# llvm decodes, whether n2a32_neon_misc / n2a32_neon_ldst must execute it, may decide either way (encoding
# the ARM ARM leaves UNDEFINED, e.g. a VTBL list running past d31), or must reject it (the two half-precision
# conversions V20 deliberately does not implement).
#
# Usage: gen_space.py out.h
import re
import subprocess
import sys

TRIPLE = "armv8a-linux-gnueabi"
MATTR = "+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8,+crypto"

SUPPORTED = {
    "vrev64", "vrev32", "vrev16", "vpaddl", "vpadal", "vcls", "vclz", "vcnt", "vmvn",
    "vqabs", "vqneg", "vcgt", "vcge", "vceq", "vcle", "vclt", "vabs", "vneg",
    "vswp", "vtrn", "vuzp", "vzip", "vmovn", "vqmovn", "vqmovun", "vshll",
    "vcvt", "vcvta", "vcvtn", "vcvtp", "vcvtm",
    "vrecpe", "vrsqrte", "vrintn", "vrinta", "vrintp", "vrintm", "vrintx", "vrintz",
    "vrintr", "vtbl", "vtbx", "vdup", "vext", "vmov", "vorr", "vbic",
    "vld1", "vld2", "vld3", "vld4", "vst1", "vst2", "vst3", "vst4",
}
# deliberately not implemented (documented in STATUS.md): must return N2A32_UNDEF
MUST_UNDEF = {"vcvt.f16.f32", "vcvt.f32.f16", "aese.8", "aesd.8", "aesmc.8", "aesimc.8",
              "sha1h.32", "sha1su1.32", "sha256su0.32"}
# llvm prints these for register numbers past d31; the ARM ARM calls the encoding UNDEFINED
UNDEF_NAMES = ("fpinst2", "mvfr")


def disassemble(words):
    inp = "".join(" ".join("0x%02x" % ((w >> (8 * i)) & 0xFF) for i in range(4)) + "\n" for w in words)
    p = subprocess.run(["llvm-mc", "--disassemble", "-triple=" + TRIPLE, "-mattr=" + MATTR],
                       input=inp.encode(), capture_output=True)
    out = [l.strip() for l in p.stdout.decode(errors="replace").splitlines() if l.strip()]
    err = p.stderr.decode(errors="replace")
    invalid = set()
    for m in re.finditer(r"^(0x[0-9a-f]{2} 0x[0-9a-f]{2} 0x[0-9a-f]{2} 0x[0-9a-f]{2})$", err, re.M):
        b = bytes(int(x, 16) for x in m.group(1).split())
        invalid.add(int.from_bytes(b, "little"))
    res = []
    oi = 0
    for w in words:
        if w in invalid:
            res.append(None)
        else:
            res.append(out[oi] if oi < len(out) else None)
            oi += 1
    if oi != len(out):
        sys.exit("alignment error: %d of %d lines consumed" % (oi, len(out)))
    return res


def classify(text):
    if text is None:
        return 0
    toks = text.replace("\t", " ").split()
    if not toks:
        return 0
    mnem = toks[0].split(".")[0]
    full = toks[0]
    if full in MUST_UNDEF:
        return 3
    if any(u in text for u in UNDEF_NAMES):
        return 0
    if mnem in SUPPORTED:
        return 2
    return 0


def main():
    out_path = sys.argv[1]
    words = []
    # 1. two-register miscellaneous and VEXT: bits 23-20 = 1D11, both U values
    for u in (0, 1):
        for a in range(16):
            for b in range(16):
                for c in (0, 1):
                    for q in (0, 1):
                        for dm in (0, 1):
                            for vm in (1, 2):
                                w = (0xF2000000 | (u << 24) | ((0xB + 4 * dm) << 20) | (a << 16) |
                                     (b << 8) | (c << 7) | (q << 6) | (dm << 5) | vm)
                                words.append(w)
    # 2. one register, modified immediate: every i/imm3/cmode/op/Q/imm4
    for i in (0, 1):
        for imm3 in range(8):
            for cmode in range(16):
                for op in (0, 1):
                    for q in (0, 1):
                        for imm4 in (0, 1, 0xF):
                            words.append(0xF2800010 | (i << 24) | (imm3 << 16) | (cmode << 8) |
                                         (op << 5) | (q << 6) | imm4)
    # 3. element/structure load/store: bits 23-20 (single/D/L/fixed), type, size, align, Rm
    for hi in (0x0, 0x2, 0x8, 0xA, 0x4, 0x6, 0xC, 0xE):
        for type in range(16):
            for size in range(4):
                for align in range(4):
                    for rm in (0xF, 0xD, 2):
                        words.append(0xF4000000 | (hi << 20) | (type << 8) | (size << 6) |
                                     (align << 4) | rm)
    words = sorted(set(words))
    res = disassemble(words)
    ok = []
    und = []
    bad = []
    for w, t in zip(words, res):
        c = classify(t)
        if c == 2:
            ok.append(w)
        elif c == 3:
            und.append(w)
        else:
            bad.append(w)
    with open(out_path, "w") as f:
        f.write("/* generated by gen_space.py: %d words, %d must execute, %d must UNDEF, "
                "%d unallocated words llvm rejects and V20 must also UNDEF */\n"
                % (len(words), len(ok), len(und), len(bad)))
        f.write("static const uint32_t space_ok[] = {\n")
        for i in range(0, len(ok), 8):
            f.write("\t" + ", ".join("0x%08Xu" % w for w in ok[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("static const uint32_t space_undef[] = {\n")
        for i in range(0, len(und), 8):
            f.write("\t" + ", ".join("0x%08Xu" % w for w in und[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("static const uint32_t space_bad[] = {\n")
        for i in range(0, len(bad), 8):
            f.write("\t" + ", ".join("0x%08Xu" % w for w in bad[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("#define SPACE_OK_COUNT %d\n#define SPACE_UNDEF_COUNT %d\n#define SPACE_BAD_COUNT %d\n"
                % (len(ok), len(und), len(bad)))
    print("gen_space: %d words, %d must execute, %d must UNDEF, %d unallocated must UNDEF"
          % (len(words), len(ok), len(und), len(bad)))


if __name__ == "__main__":
    main()
