#!/bin/bash
# SPDX-License-Identifier: MIT
#
# gen_selftest_prog.sh -- turn daemon/test/selftest_{a32,t32}.s into the byte array header the daemon embeds.
# Prints the header to stdout; writes only under /tmp/n2hw-ip.  No arguments.
#
# llvm-mc is the assembler oracle: run_tests.sh runs this script and diffs its output against the committed
# daemon/n2vcd_selftest_prog.h, so a blob that no longer matches its assembly fails the suite.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
TMP=/tmp/n2hw-ip/gen
rm -rf "$TMP"
mkdir -p "$TMP"

for src in selftest_a32 selftest_t32; do
	llvm-mc -triple=armv7-none-eabi -filetype=obj "$HERE/$src.s" -o "$TMP/$src.o"
	llvm-objcopy -O binary --only-section=.text "$TMP/$src.o" "$TMP/$src.bin"
done

# One blob per file plus the symbol offsets/sizes from the object (no hand-written numbers).
nm_offsets() {  # nm_offsets <obj> -> "sym:0xoff:0xsize ..." for the functions we use
	llvm-nm -S --defined-only "$1" | awk '{ printf "%s:0x%s:0x%s ", $4, $1, $2 }'
}

blob_print() {  # blob_print <cname> <bin>
	local name=$1 file=$2
	local size
	size=$(stat -c %s "$file")
	echo "static const unsigned char $name[] = {"
	local i=0
	while [ $i -lt "$size" ]; do
		local line
		line=$(od -An -v -tx1 -N16 -j "$i" "$file" | tr -s ' ' | sed 's/^ //; s/ $//; s/ /,0x/g; s/^/0x/')
		printf '\t%s,\n' "$line"
		i=$((i + 16))
	done
	echo "};"
	echo "enum { ${name^^}_BYTES = $size };"
}

echo "/* SPDX-License-Identifier: MIT */"
echo "/*"
echo " * n2vcd_selftest_prog.h -- GENERATED by daemon/test/gen_selftest_prog.sh from daemon/test/selftest_a32.s and"
echo " * daemon/test/selftest_t32.s with llvm-mc -triple=armv7-none-eabi.  Do not edit; run_tests.sh regenerates this file"
echo " * and fails if the committed bytes differ from what llvm-mc produces."
echo " */"
echo "#ifndef N2VCD_SELFTEST_PROG_H"
echo "#define N2VCD_SELFTEST_PROG_H"
blob_print n2sv_a32 "$TMP/selftest_a32.bin"
blob_print n2sv_t32 "$TMP/selftest_t32.bin"
echo ""
# Symbol offsets inside each blob (decimal byte offsets, C-friendly).
for pair in "a32 selftest_a32" "t32 selftest_t32"; do
	set -- $pair
	prefix=$1
	obj=$2
	echo "/* $obj.o: $(nm_offsets "$TMP/$obj.o") */"
done
# Emit the offsets/line lengths as enums parsed from nm.
a32_loop_off=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_loop"{print strtonum("0x"$1)}')
a32_loop_size=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_loop"{print strtonum("0x"$2)}')
a32_ok_off=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_ok"{print strtonum("0x"$1)}')
a32_ok_size=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_ok"{print strtonum("0x"$2)}')
a32_fault_off=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_fault"{print strtonum("0x"$1)}')
a32_fault_size=$(llvm-nm -S --defined-only "$TMP/selftest_a32.o" | awk '$4=="selftest_a32_fault"{print strtonum("0x"$2)}')
t32_loop_off=$(llvm-nm -S --defined-only "$TMP/selftest_t32.o" | awk '$4=="selftest_t32_loop"{print strtonum("0x"$1)}')
t32_loop_size=$(llvm-nm -S --defined-only "$TMP/selftest_t32.o" | awk '$4=="selftest_t32_loop"{print strtonum("0x"$2)}')
t32_ok_off=$(llvm-nm -S --defined-only "$TMP/selftest_t32.o" | awk '$4=="selftest_t32_ok"{print strtonum("0x"$1)}')
t32_ok_size=$(llvm-nm -S --defined-only "$TMP/selftest_t32.o" | awk '$4=="selftest_t32_ok"{print strtonum("0x"$2)}')
cat <<EOF
enum {
	N2SV_A32_LOOP_OFF = $a32_loop_off,  N2SV_A32_LOOP_LEN = $a32_loop_size,
	N2SV_A32_OK_OFF   = $a32_ok_off,    N2SV_A32_OK_LEN   = $a32_ok_size,
	N2SV_A32_FAULT_OFF = $a32_fault_off, N2SV_A32_FAULT_LEN = $a32_fault_size,
	N2SV_T32_LOOP_OFF = $t32_loop_off,  N2SV_T32_LOOP_LEN = $t32_loop_size,
	N2SV_T32_OK_OFF   = $t32_ok_off,    N2SV_T32_OK_LEN   = $t32_ok_size
};
#endif /* N2VCD_SELFTEST_PROG_H */
EOF
