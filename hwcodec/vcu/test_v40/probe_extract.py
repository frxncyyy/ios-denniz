"""V40: turn the armv7a .probe section of layout_probe.o into a C initialiser.

argv[1] = object built from layout_probe.c for armv7a-linux-gnueabi
argv[2] = output header (probe_values.h)

Uses llvm-objcopy to dump the section as raw bytes (the section is a plain u32 array, so no
relocations), then unpacks little-endian.  Independent of the host's own struct layout.
"""
import subprocess
import struct
import sys

obj, out = sys.argv[1], sys.argv[2]
binpath = out + ".probe.bin"
subprocess.run(["llvm-objcopy", "-O", "binary", "--only-section=.probe", obj, binpath],
               check=True)
with open(binpath, "rb") as f:
    data = f.read()
if len(data) % 4 != 0 or len(data) == 0:
    sys.exit("V40: .probe section has %d bytes" % len(data))
words = list(struct.unpack("<%dI" % (len(data) // 4), data))
if words[-1] != 0x56433430:
    sys.exit("V40: .probe sentinel is 0x%08x, not 0x56433430" % words[-1])

with open(out, "w") as f:
    f.write("/* generated by probe_extract.py from layout_probe.o -- do not edit */\n")
    f.write("#define PROBE_WORDS %du\n" % len(words))
    f.write("#define PROBE_TABLE_INIT { \\\n")
    for i in range(0, len(words), 6):
        chunk = ", ".join("0x%08xu" % w for w in words[i:i + 6])
        f.write("\t" + chunk + ", \\\n")
    f.write("}\n")
print("V40: probe words %d, sentinel 0x%08x" % (len(words), words[-1]))
