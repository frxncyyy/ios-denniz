/* Compile the frontend's internal surface-conversion shaders (A3: YCbCr and
 * XR IOSurface decode shadows converted on the GPU) with the actual arch9
 * compiler, as generate_preload.c does for the bridge's LOAD shaders.
 * argv: preload.vert.spv ycbcr_convert.frag.spv xr_convert.frag.spv
 * Output (stdout): nord2_convert.h for compositor_submit.inc. Every binding,
 * its kind and the push-constant size are asserted against what the
 * frontend binds, so a compiler change cannot silently move them. */
#include "tegu/mali_graphics_compiler.h"
#include <stdio.h>
#include <stdlib.h>
#include <assert.h>
static void *read_file(const char *path,size_t *size){
 FILE *f=fopen(path,"rb");assert(f);fseek(f,0,SEEK_END);long n=ftell(f);rewind(f);assert(n>0&&n<1048576);
 void *p=malloc(n);assert(p&&fread(p,1,n,f)==(size_t)n);fclose(f);*size=n;return p;
}
static void bytes(const char *name,const struct tegu_mali_graphics *g){
 printf("static const uint8_t %s[]={",name);for(size_t j=0;j<g->size;j++)printf("%u,",g->code[j]);puts("};");
}
static int emit(const void *v,size_t vn,const char *path,const char *name,unsigned textures,unsigned push,int with_vs){
 size_t fn;void *f=read_file(path,&fn);
 struct tegu_mali_graphics vs={0},fs={0};struct tegu_mali_graphics_pair2 p={0};struct tegu_mali_generic_plan plan={0};char err[512]={0};
 int e=tegu_mali_compile_generic_pair(v,vn,f,fn,&vs,&fs,&p,&plan,err,sizeof(err));
 if(e){fprintf(stderr,"%s compile %d: %s\n",name,e,err);return 1;}
 /* No TLS, no varyings, exactly `textures` combined samplers at bindings
  * 0..textures-1, fragment-only, and at most `push` bytes of push data. */
 assert(!vs.tls&&!fs.tls&&!p.fs_uses_ld_var&&!plan.reads_framebuffer&&plan.count==textures);
 unsigned seen=0; /* the plan lists them in any order */
 for(unsigned i=0;i<plan.count;i++){
  assert(plan.bindings[i].binding<textures&&plan.bindings[i].kind==TEGU_MALI_GENERIC_COMBINED&&!(seen&(1u<<plan.bindings[i].binding)));
  seen|=1u<<plan.bindings[i].binding;}
 assert(fs.push_bytes<=push&&fs.fau_words<=32+push/4);
 if(with_vs)bytes("n2_convert_vs",&vs);
 char code[96];snprintf(code,sizeof(code),"%s_fs",name);bytes(code,&fs);
 printf("static const struct tegu_generic_draw_shader %s_shader={.vertex_code=n2_convert_vs,.fragment_code=%s,.vertex_bytes=sizeof(n2_convert_vs),.fragment_bytes=%zu,.vertex_registers=%u,.fragment_registers=%u,.secondary_registers=%u,.vertex_fau_words=%u,.fragment_fau_words=%u,.position_offset=%u,.secondary_offset=%u,.varying_bytes=%u,.vertex_preload=%lluull,.fragment_preload=%lluull,.secondary_preload=%lluull,.blend={.version=1,.write_mask=15}};\n",
  name,code,fs.size,vs.registers,fs.registers,p.secondary_registers,vs.fau_words,fs.fau_words,p.position_offset,p.secondary_offset,p.generic_size_B,
  (unsigned long long)vs.preload,(unsigned long long)fs.preload,(unsigned long long)p.secondary_preload);
 printf("#define %s_PUSH_BYTES %uu\n",name,fs.push_bytes);
 free(f);tegu_mali_graphics_free(&vs);tegu_mali_graphics_free(&fs);return 0;
}
int main(int argc,char **argv){
 assert(argc==4);size_t vn;void *v=read_file(argv[1],&vn);
 puts("/* Generated by tools/generate_convert.c from tests/shaders/nord2_{preload.vert,ycbcr_convert.frag,xr_convert.frag}\n"
      " * with pinned Mesa81daea6, arch9. Do not edit. */");
 puts("#ifndef NORD2_CONVERT_H\n#define NORD2_CONVERT_H");
 int r=emit(v,vn,argv[2],"n2_ycbcr_convert",3,64,1)||emit(v,vn,argv[3],"n2_xr_convert",2,16,0);
 puts("#endif");
 free(v);return r;
}
