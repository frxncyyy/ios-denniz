#!/usr/bin/env python3
"""Generate gpu/metal/tegu/xr_decode_table.h: IEEE half bits of Apple's
extended-range (XR) 10-bit codes, for the frontend's decode shadows.

value(c) = (c - 384) / 510 (Metal BGR10_XR / BGRA10_XR colour);
_sRGB twins: the sign-preserving sRGB transfer of that value;
alpha: the value clamped to [0, 1].  Halves are rounded to nearest even.
Also tegu_srgb_knots_8192[513]: K[j] = the step of 1/8192 nearest
8192 * srgb_to_linear(16 j / 8192), the knots of Metal's YCbCr _sRGB decode
(metal2vulkan bind/ycbcr_convert.rs; reproduced exactly by this formula).
Run: python3 gpu/tools/gen_xr_decode_table.py [--check]"""
import struct, sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'metal/tegu/xr_decode_table.h'


def half(v):
    return struct.unpack('<H', struct.pack('<e', v))[0]  # round-to-nearest-even


def srgb_to_linear(v):
    a = abs(v)
    l = a / 12.92 if a <= 0.04045 else ((a + 0.055) / 1.055) ** 2.4
    return -l if v < 0 else l


def tables():
    lin = [half((c - 384) / 510) for c in range(1024)]
    srgb = [half(srgb_to_linear((c - 384) / 510)) for c in range(1024)]
    alpha = [half(min(1.0, max(0.0, (c - 384) / 510))) for c in range(1024)]
    return lin, srgb, alpha


def knots():
    k = [round(8192 * srgb_to_linear(16 * j / 8192)) for j in range(513)]
    rows = [','.join(str(v) for v in k[i:i + 16]) for i in range(0, 513, 16)]
    return 'static const uint16_t tegu_srgb_knots_8192[513]={\n%s};\n' % ',\n'.join(rows)


def srgb8_tables():
    to_linear = [srgb_to_linear(c / 255) for c in range(256)]
    # linear value at which the sRGB encode crosses code c+0.5 (c = 0..254)
    thresholds = [srgb_to_linear((c + 0.5) / 255) for c in range(255)]
    def farr(name, values):
        rows = [','.join('%.9ef' % v for v in values[i:i + 8]) for i in range(0, len(values), 8)]
        return 'static const float %s[%d]={\n%s};\n' % (name, len(values), ',\n'.join(rows))
    return farr('tegu_srgb8_to_linear', to_linear) + farr('tegu_srgb8_encode_threshold', thresholds)


def render():
    lin, srgb, alpha = tables()
    def arr(name, values):
        rows = [','.join('0x%04x' % v for v in values[i:i + 16]) for i in range(0, 1024, 16)]
        return 'static const uint16_t %s[1024]={\n%s};\n' % (name, ',\n'.join(rows))
    return ('/* Generated by gpu/tools/gen_xr_decode_table.py; do not edit. */\n'
            '#ifndef TEGU_XR_DECODE_TABLE_H\n#define TEGU_XR_DECODE_TABLE_H\n#include <stdint.h>\n' +
            arr('tegu_xr_half_linear', lin) + arr('tegu_xr_half_srgb', srgb) + arr('tegu_xr_half_alpha', alpha) +
            knots() + srgb8_tables() +
            '#endif\n')


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
