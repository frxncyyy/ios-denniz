#!/usr/bin/env python3
"""Generate gpu/metal/srgb8_encode_table.h: the 255 linear thresholds of the
8-bit sRGB encode used for sRGB render-target clear colours.

Mesa 81daea66 pan_pack_color (lib/pan_clear.c) packs an sRGB target's clear
colour as roundeven(255 * linear_to_srgb(saturate(c))) into the R8G8B8A8 tile
word.  linear_to_srgb is monotone, so the code is the number of thresholds
T[k] = srgb_to_linear((k + 0.5) / 255), k = 0..254, that the linear value
reaches.  The header lets freestanding (no libm) code reproduce the encode.
Run: python3 gpu/tools/gen_srgb8_encode_table.py [--check]"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'metal/srgb8_encode_table.h'


def srgb_to_linear(s):
    return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4


def render():
    t = [srgb_to_linear((k + 0.5) / 255.0) for k in range(255)]
    rows = []
    for i in range(0, 255, 5):
        rows.append('    ' + ', '.join(repr(v) for v in t[i:i + 5]) + ',')
    return ('/* Generated by gpu/tools/gen_srgb8_encode_table.py; do not edit. */\n'
            '#ifndef NORD2_SRGB8_ENCODE_TABLE_H\n#define NORD2_SRGB8_ENCODE_TABLE_H\n'
            '/* T[k] = srgb_to_linear((k + 0.5) / 255): an sRGB 8-bit code is the\n'
            ' * number of thresholds a saturated linear value reaches. */\n'
            'static const double n2r_srgb8_thresholds[255] = {\n' + '\n'.join(rows) + '\n};\n'
            'static inline unsigned n2r_srgb8_encode(double linear)\n{\n'
            '    unsigned lo = 0, hi = 255;\n'
            '    if (!(linear > 0.0)) return 0;\n'
            '    while (lo < hi) { unsigned mid = (lo + hi) / 2; if (linear >= n2r_srgb8_thresholds[mid]) lo = mid + 1; else hi = mid; }\n'
            '    return lo;\n}\n#endif\n')


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
