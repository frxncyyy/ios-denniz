# mkenc.py -- turn test_v10/encodings.txt ("label|assembly line") into a C header of
# instruction words using llvm-mc as the assembler.  Every encoding used by the V10
# tests comes from here; none is typed by hand.
#
#   llvm-mc -triple=armv7a-linux-gnueabi \
#           -mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8 --show-encoding
#
# Exit status 0 and a header on stdout/success; any assembler error is fatal.

import re
import subprocess
import sys


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: mkenc.py encodings.txt out.h\n")
        return 2
    src, out = sys.argv[1], sys.argv[2]
    labels, lines = [], []
    with open(src, "r", encoding="utf-8") as f:
        for raw in f:
            raw = raw.strip()
            if not raw or raw.startswith("#"):
                continue
            label, asm = raw.split("|", 1)
            labels.append(label.strip())
            lines.append(asm.strip())
    text = "\t.syntax unified\n\t.arm\n\t.text\n" + "".join("\t%s\n" % a for a in lines)
    cmd = ["llvm-mc", "-triple=armv7a-linux-gnueabi",
           "-mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8", "--show-encoding"]
    p = subprocess.run(cmd, input=text, capture_output=True, text=True)
    if p.returncode != 0:
        sys.stderr.write(p.stdout + p.stderr)
        sys.stderr.write("mkenc.py: llvm-mc failed\n")
        return 1
    words = []
    for line in p.stdout.splitlines():
        m = re.search(r"@ encoding: \[([0-9a-fA-Fx,]+)\]", line)
        if not m:
            continue
        bs = [int(x, 16) for x in m.group(1).split(",")]
        if len(bs) != 4:
            sys.stderr.write("mkenc.py: unexpected encoding length in: %s\n" % line)
            return 1
        words.append(bs[0] | bs[1] << 8 | bs[2] << 16 | bs[3] << 24)
    if len(words) != len(labels):
        sys.stderr.write("mkenc.py: %d encodings for %d instructions\n" %
                         (len(words), len(labels)))
        return 1
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* SPDX-License-Identifier: MIT */\n")
        f.write("/* Generated by mkenc.py from encodings.txt with llvm-mc; do not edit. */\n")
        f.write("#ifndef ENC_V10_H\n#define ENC_V10_H\n")
        for label, w in zip(labels, words):
            f.write("#define E_%s 0x%08xu\n" % (label.upper(), w))
        f.write("#endif\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
