"""Assemble test_v17/vectors.s and test_v17/vectors_t32.s with llvm-mc and emit enc_v17.h.

Every enc_* label must name exactly one 32-bit instruction.  The encoding is read back from the
object file llvm-mc produced (never typed in by hand), so the test header is a direct transcription
of the assembler's output.  llvm-objdump cannot decode VFP mnemonics (it prints <unknown> for them),
but it does print the instruction word(s), which is all the generator needs.
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "enc_v17.h"
TMP = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("/tmp/n2hw-V17")

SOURCES = [
    (HERE / "vectors.s", ["--triple=armv8a-linux-gnueabi"]),
    (HERE / "vectors_t32.s", ["--triple=thumbv8a-linux-gnueabi"]),
]
MATTR = ["--mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8"]


def fail(msg):
    sys.stderr.write("gen_enc: %s\n" % msg)
    sys.exit(1)


found = {}
for src, triple in SOURCES:
    obj = TMP / (src.stem + ".o")
    subprocess.run(["llvm-mc", *triple, *MATTR, "-filetype=obj", str(src), "-o", str(obj)],
                   check=True)
    dis = subprocess.run(["llvm-objdump", "-d", *triple, *MATTR, str(obj)],
                         capture_output=True, text=True, check=True).stdout
    sym = None
    for line in dis.splitlines():
        m = re.match(r"^([0-9a-f]+) <(enc_[A-Za-z0-9_]+)>:$", line.strip())
        if m:
            sym = m.group(2)
            continue
        if sym is None:
            continue
        m = re.match(r"^\s*([0-9a-f]+):\s+([0-9a-f]{8})\s+(\S.*)$", line)
        if m:
            word = int(m.group(2), 16)
        else:
            m = re.match(r"^\s*([0-9a-f]+):\s+([0-9a-f]{4})\s+([0-9a-f]{4})\s+(\S.*)$", line)
            if not m:
                continue
            word = (int(m.group(2), 16) << 16) | int(m.group(3), 16)
        if sym in found:
            fail("duplicate label %s" % sym)
        found[sym] = word
        sym = None

if not found:
    fail("no enc_ labels found")

out = ["/* generated by gen_enc.py from vectors.s / vectors_t32.s -- do not edit */",
       "#ifndef V17_ENC_H", "#define V17_ENC_H", ""]
for name in sorted(found):
    out.append("#define ENC_%s 0x%08Xu" % (name[len("enc_"):], found[name]))
out += ["", "#endif"]
OUT.write_text("\n".join(out) + "\n")
print("gen_enc: %d encodings -> %s" % (len(found), OUT))
