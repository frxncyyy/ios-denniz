#!/usr/bin/env python3
"""SPDX-License-Identifier: MIT

gen_decode_oracle.py -- generate a decode oracle for the V18 instruction space.

For every (U, size, opc, bit4, Q) combination and three register patterns, the word is handed to
`llvm-mc --disassemble` (the same tool that produced every encoding in the tests).  The expected
result of n2a32_neon_3same() is:

    llvm-mc decodes it as an instruction and it is not in the deliberately unimplemented SHA space
        -> N2A32_OK
    llvm-mc rejects it, or it is SHA1/SHA256
        -> N2A32_UNDEF

Two additional groups probe the Q-form register constraints with words derived from valid ones:
Q form with an odd register number and Q form with one of the D/N/M high bits set must be UNDEF
(both are architecturally UNPREDICTABLE; llvm-mc rejects them as invalid encodings).

Output (argv[1]): decode_oracle.inc, an array initialiser for struct oracle_case.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))


def disasm(words):
    data = "".join("0x%02x 0x%02x 0x%02x 0x%02x\n" %
                   (w & 0xff, (w >> 8) & 0xff, (w >> 16) & 0xff, (w >> 24) & 0xff) for w in words)
    p = subprocess.run(["llvm-mc", "--disassemble", "-triple=armv8a-linux-gnueabi",
                        "-mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8"],
                       input=data, capture_output=True, text=True)
    bad = set(int(m.group(1)) for m in
              re.finditer(r"<stdin>:(\d+):1: warning: invalid instruction encoding", p.stderr))
    out = [l.strip() for l in p.stdout.splitlines() if l.strip()]
    res = []
    oi = 0
    for i, w in enumerate(words):
        if (i + 1) in bad:
            res.append(None)
        else:
            res.append(out[oi])
            oi += 1
    assert oi == len(out), (oi, len(out))
    return res


def sha_space(u, size, opc, b4, q):
    del u
    return opc == 0xC and b4 == 0 and q == 1 and size in (0, 1, 2, 3)


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: gen_decode_oracle.py outdir\n")
        return 2
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)

    patterns = {0: [0x00000000, 0x00021003, 0x004100A2],
                1: [0x00000040, 0x00042046, 0x000EC04A]}
    words = []
    meta = []
    for u in (0, 1):
        for size in (0, 1, 2, 3):
            for opc in range(16):
                for b4 in (0, 1):
                    for q in (0, 1):
                        for pat in patterns[q]:
                            w = 0xF2000000 | (u << 24) | (size << 20) | (opc << 8) | (b4 << 4) | pat
                            words.append(w)
                            meta.append((u, size, opc, b4, q))
    res = disasm(words)

    lines = []
    n_ok = n_undef = 0
    for w, r, m in zip(words, res, meta):
        u, size, opc, b4, q = m
        if r is not None and not sha_space(u, size, opc, b4, q):
            expect = 1
            n_ok += 1
        else:
            expect = 0
            n_undef += 1
        text = (r if r is not None else "invalid").replace('"', "'")
        lines.append('{ 0x%08xu, %d, "%s" },' % (w, expect, text))

    # Derived words: a Q form with one of its three D-register numbers made odd.  The D/N/M bits
    # on their own are legal (they encode Q8-Q15), but an odd D-register number is UNPREDICTABLE
    # and every such word must be UNDEF.
    n_derived = 0
    for w, r, m in zip(words, res, meta):
        u, size, opc, b4, q = m
        if r is None or q != 1 or sha_space(u, size, opc, b4, q):
            continue
        vd = (w >> 12) & 0xF
        odd = w if (vd & 1) else (w ^ 0x1000)          # make Vd odd (bit 12)
        lines.append('{ 0x%08xu, 0, "derived: Q form with odd Vd" },' % odd)
        n_derived += 1
        vn = (w >> 16) & 0xF
        if not (vn & 1):
            lines.append('{ 0x%08xu, 0, "derived: Q form with odd Vn" },' % (w ^ 0x10000))
            n_derived += 1
        vm = w & 0xF
        if not (vm & 1):
            lines.append('{ 0x%08xu, 0, "derived: Q form with odd Vm" },' % (w ^ 1))
            n_derived += 1

    path = os.path.join(outdir, "decode_oracle.inc")
    with open(path, "w") as f:
        f.write("/* SPDX-License-Identifier: MIT */\n")
        f.write("/* Generated by gen_decode_oracle.py from llvm-mc; do not edit. */\n")
        for line in lines:
            f.write(line + "\n")
    print("V18-ORACLE words %d ok %d undef %d derived-undef %d"
          % (len(words), n_ok, n_undef, n_derived))
    return 0


if __name__ == "__main__":
    sys.exit(main())
