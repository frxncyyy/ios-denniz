"""Extract V14's 16-bit encodings from an assembled t16_enc.s.

The assembly text and the object file come from llvm-mc (run_tests.sh).  Every
source instruction line must have assembled to exactly one 2-byte instruction;
the lines annotated with "@ E_<name>" become "#define E_<name> 0x....u" in the
generated header.  No encoding is ever written by hand.
"""
import re
import sys


def instruction_lines(path):
    out = []
    for lineno, raw in enumerate(open(path, encoding="utf-8"), 1):
        text = raw.split("@", 1)[0].strip()
        if not text:
            continue
        if text.startswith("."):       # directives
            continue
        if text.endswith(":"):         # labels
            continue
        out.append((lineno, text, raw))
    return out


def objdump_instructions(path):
    out = []
    for raw in open(path, encoding="utf-8"):
        m = re.match(r"\s*([0-9a-f]+):\s+([0-9a-f]+)\s", raw)
        if m:
            out.append((int(m.group(1), 16), m.group(2).lower()))
    return out


def show_encodings(path):
    """One entry per source instruction: the llvm-mc --show-encoding bytes, or
    None when the line contains a relocation/fixup marker (branches)."""
    out = []
    for raw in open(path, encoding="utf-8"):
        if "@ encoding:" not in raw:
            continue
        body = raw.split("@ encoding:", 1)[1].strip()
        if not (body.startswith("[") and body.endswith("]")):
            continue
        toks = [t.strip() for t in body[1:-1].split(",")]
        if len(toks) == 2 and all(re.fullmatch(r"0x[0-9a-fA-F]{2}", t) for t in toks):
            out.append(int(toks[0], 16) | (int(toks[1], 16) << 8))
        else:
            out.append(None)          # fixup (branch immediate) or wide form
    return out


def main():
    src, dump, show, header = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
    ins = instruction_lines(src)
    dis = objdump_instructions(dump)
    if len(ins) != len(dis):
        sys.stderr.write(
            "V14 encoding extraction: %d source instructions but %d disassembled\n"
            % (len(ins), len(dis)))
        return 1
    shown = show_encodings(show)
    if len(shown) != len(ins):
        sys.stderr.write(
            "V14 encoding extraction: %d source instructions but %d --show-encoding lines\n"
            % (len(ins), len(shown)))
        return 1
    defines = []
    seen = set()
    crosschecked = 0
    for (lineno, text, raw), (addr, enc), sh in zip(ins, dis, shown):
        if sh is not None:
            if sh != int(enc, 16):
                sys.stderr.write(
                    "V14 encoding extraction: %s:%d --show-encoding 0x%04x != objdump %s\n"
                    % (src, lineno, sh, enc))
                return 1
            crosschecked += 1
        if len(enc) != 4:
            sys.stderr.write(
                "V14 encoding extraction: %s:%d assembled wide (%s bytes): %s\n"
                % (src, lineno, len(enc) // 2, text))
            return 1
        m = re.search(r"@\s*(E_[A-Za-z0-9_]+)\s*$", raw.rstrip())
        if not m:
            continue
        name = m.group(1)
        if name in seen:
            sys.stderr.write("V14 encoding extraction: duplicate %s\n" % name)
            return 1
        seen.add(name)
        defines.append("#define %s 0x%su" % (name, enc))
    if not defines:
        sys.stderr.write("V14 encoding extraction: no E_* markers found\n")
        return 1
    with open(header, "w", encoding="utf-8") as f:
        f.write("/* generated by gen_enc.py from %s -- do not edit */\n" % src)
        f.write("#ifndef V14_ENCODINGS_H\n#define V14_ENCODINGS_H\n")
        f.write("\n".join(defines))
        f.write("\n#endif\n")
    print("V14 encodings: %d instructions, %d named, %d cross-checked against --show-encoding"
          % (len(ins), len(defines), crosschecked))
    return 0


if __name__ == "__main__":
    sys.exit(main())
