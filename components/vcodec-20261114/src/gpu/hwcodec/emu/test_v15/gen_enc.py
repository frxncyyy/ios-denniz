"""Assemble test_v15/vectors.s with llvm-mc and emit enc_gen.h.

Every ``enc_*`` label must be followed by exactly one 32-bit Thumb instruction;
the generator reads the encodings back from the object file the assembler
produced (so PC-relative fixups such as ADR are resolved by llvm-mc, never typed
in by hand) and writes one ``#define ENC_<label> 0x........u`` per vector.
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
import os
TMP = Path(os.environ.get("N2HW_TMP", "/tmp/n2hw-V15"))
SRC = HERE / "vectors.s"
OBJ = Path(sys.argv[1]) / "vectors.o" if len(sys.argv) > 1 else TMP / "vectors.o"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else TMP / "enc_gen.h"
TRIPLE = ["--triple=thumbv7a-linux-gnueabi"]
MATTR = ["--mattr=+neon,+vfp4,+hwdiv,+hwdiv-arm,+fp-armv8"]


def fail(msg):
    sys.stderr.write("gen_enc: %s\n" % msg)
    sys.exit(1)


subprocess.run(["llvm-mc", *TRIPLE, *MATTR, "-filetype=obj", str(SRC), "-o", str(OBJ)],
               check=True)
dis = subprocess.run(["llvm-objdump", "-d", *TRIPLE, *MATTR, str(OBJ)],
                     capture_output=True, text=True, check=True).stdout

# symbol address -> name
symbols = {}
for line in dis.splitlines():
    m = re.match(r"^([0-9a-f]+) <(enc_[A-Za-z0-9_]+)>:$", line.strip())
    if m:
        addr = int(m.group(1), 16)
        if addr in symbols:
            fail("two enc_ labels share address 0x%x (%s, %s)"
                 % (addr, symbols[addr], m.group(2)))
        symbols[addr] = m.group(2)

# address -> list of halfwords on that line
insns = {}
for line in dis.splitlines():
    m = re.match(r"^\s*([0-9a-f]+):\s+([0-9a-f]{4})(?:\s+([0-9a-f]{4}))?\s+(\S.*)$", line)
    if not m:
        continue
    addr = int(m.group(1), 16)
    insns[addr] = (m.group(2), m.group(3), m.group(4))

if not symbols:
    fail("no enc_ labels found in the disassembly")

out = ["/* generated by gen_enc.py from vectors.s -- do not edit */",
       "#ifndef V15_ENC_GEN_H",
       "#define V15_ENC_GEN_H",
       ""]
for addr in sorted(symbols):
    name = symbols[addr]
    if addr not in insns:
        fail("%s: no instruction at 0x%x" % (name, addr))
    lo, hi, text = insns[addr]
    if hi is None:
        fail("%s: assembles to a 16-bit instruction (%s); add .w or change operands"
             % (name, text))
    word = (int(lo, 16) << 16) | int(hi, 16)
    out.append("#define ENC_%s 0x%08Xu\t/* %s */"
               % (name[len("enc_"):], word, text))
out += ["", "#endif"]
OUT.write_text("\n".join(out) + "\n")
print("gen_enc: %d vectors -> %s" % (len(symbols), OUT))
