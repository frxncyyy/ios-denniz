/*
 * n2shim_props.c -- the Android property table behind the property_get() shim (package V34).
 *
 * Why a table: the five vendor objects call property_get() about 70 times, almost all of it for MediaTek debug
 * switches whose stock value is 'not set' (Android then hands the caller its own compiled default, which is 0 for
 * every one of them). Nothing in the vendor code needs a real property service on this phone, so the table answers
 * two kinds of keys:
 *
 *   value != NULL   the phone really has this property with this value. Every entry here comes from the phone's
 *                   own build.prop files (evidence in the entry's comment): /vendor/build.prop extracted to
 *                   gpu/build/cam-vendor-20261109/vfs, and /system/build.prop plus the real /vendor/build.prop
 *                   from gpu/build/baseband-recon-20261104. property_get() copies the value.
 *
 *   value == NULL   the key is known and 'not present on this phone': property_get() copies the CALLER'S DEFAULT
 *                   and returns its length, exactly like Android's property service for an unset property. The
 *                   entry still exists so that (a) the key set is documented and (b) an unknown key (a typo, a new
 *                   vendor string) can be told apart and reported once by the shim.
 *
 * The key set is every string in the five vendor objects that `strings -a` reports as a property-shaped name with
 * one of the prefixes ro. / persist. / vendor. (203 keys). test_v34/run_tests.sh regenerates that list with the
 * real `strings` and the test fails if a key is neither in this table nor in its explicit 'default is fine' list,
 * so a vendor object update cannot silently introduce an unhandled property.
 *
 * Lookup is a linear scan over the sorted table: 203 strcmp against the 70 calls of a process start-up is far
 * below anything measurable, and it keeps the file dependency-free (no qsort, no bsearch, no allocation).
 * No locking: the table is read-only after load, and the 'seen' set lives in n2shim_android.c.
 *
 * INTERFACE: this package owns only n2shim_android.c, n2shim_props.c and test_v34/, so there is no shared header.
 * struct n2prop_entry, n2shim_props[] and n2shim_prop_find() are declared identically here, in n2shim_android.c
 * and in test_v34/t_props.c; keep the three declarations in step.
 *
 * The table is generated from the evidence above by test_v34/gen_props.py (kept to make a re-generation easy);
 * the committed C text is the source of truth.
 */
