/*
 * Exact, case-sensitive lookup (Android property names are case-sensitive: 'vendor.mtk.venc.h264.DynamicI' and
 * 'vendor.mtk.venc.h264.dynamici' are different keys). Returns NULL when the key is not in the table.
 */
const struct n2prop_entry *n2shim_prop_find(const char *key)
{
	const struct n2prop_entry *e;

	if (key == NULL)
		return NULL;
	for (e = n2shim_props; e->key != NULL; e++)
		if (e->key[0] == key[0] && strcmp(e->key, key) == 0)
			return e;
	return NULL;
}

