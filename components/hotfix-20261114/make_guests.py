#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of hotfix-20261114 (run on the host, writes only here).
hotfix1     = dk1 (driverkitd job out of the launchd cache) + posteroff1 [AegirPoster] + diag1 (n2sample also samples coreduetd/aggregated)
hotfix1lean = the same with posteroff1 [AegirPoster, PridePosterExtension, WeatherPoster] (frees GPU contexts: 7 clients maximum in the kernel)
dk1only     = dk1 alone (no LaunchServices rescan)
the -undo guests run the blocks in reverse order; the *roundtrip guests do install, install again, undo, undo again with manifests."""
import hashlib, json
from pathlib import Path
H = Path(__file__).resolve().parent
blocks = {n: (H / f'block-{n}.py').read_text() for n in ('dk1', 'posteroff1', 'diag1')}
AEGIR = ['/System/Library/CoreServices/AegirProxyApp.app/PlugIns/AegirPoster.appex/Info.plist']
LEAN = AEGIR + ['/System/Library/PrivateFrameworks/PridePoster.framework/PlugIns/PridePosterExtension.appex/Info.plist',
                '/Applications/Weather.app/PlugIns/WeatherPoster.appex/Info.plist',
                '/System/Library/AppPlaceholders/Weather.app/PlugIns/WeatherPoster.appex/Info.plist']   # the placeholder copy too, whichever LaunchServices registers
HEAD = 'set +e\n# %s (generated by hotfix-20261114/make_guests.py from block-*.py; see those files for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def body(name, parts, receipt, done=True):
    s = HEAD % name
    for b, undo, off in parts:
        s += "python3 - <<'GUEST'\nUNDO=%s\nOFF=%r\n%sGUEST\n" % (undo, off, blocks[b])
    t = TAIL % (name, receipt)
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
def inst(off): return [('dk1', False, []), ('posteroff1', False, off), ('diag1', False, [])]
def undo(off): return [('diag1', True, []), ('posteroff1', True, off), ('dk1', True, [])]
GUESTS = {'hotfix1': (inst(AEGIR), 'metal receipt launchd sha', 'driverkitd job off + AegirPoster not registered + n2sample samples coreduetd', AEGIR),
          'hotfix1-undo': (undo(AEGIR), 'metal receipt launchd sha', 'undo of hotfix1', AEGIR),
          'hotfix1lean': (inst(LEAN), 'metal receipt launchd sha', 'hotfix1 + Pride and Weather posters not registered', LEAN),
          'hotfix1lean-undo': (undo(LEAN), 'metal receipt launchd sha', 'undo of hotfix1lean', LEAN),
          'dk1only': ([('dk1', False, [])], 'metal receipt launchd sha', 'driverkitd job off', []),
          'dk1only-undo': ([('dk1', True, [])], 'metal receipt launchd sha', 'undo of dk1only', [])}
for name, (parts, receipt, purpose, off) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts, receipt))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': name, 'posteroff1': off, 'blocks_sha256': {k: hashlib.sha256(v.encode()).hexdigest() for k, v in blocks.items()}}, indent=1, sort_keys=True) + '\n')
MAN = r'''set +e
mkdir -p /tmp
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,glob,plistlib
R='/work/root'; out={}
for top in ['/private/var/db/nord2-stock','/System/Library/CoreServices/AegirProxyApp.app','/System/Library/PrivateFrameworks/PridePoster.framework','/Applications/Weather.app/PlugIns','/System/Library/AppPlaceholders/Weather.app/PlugIns','/System/Library/xpc','/System/Library/ExtensionKit','/System/Library/FeatureFlags']+[p[len(R):] for p in glob.glob(R+'/private/var/mobile/Containers/Data/InternalDaemon/*/Library/Caches')]:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p) and not os.path.islink(p) and (st.st_size<4<<20): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
out['sha:metal-receipt']=hashlib.sha256(open(R+'/private/var/db/nord2-metal/receipt.json','rb').read()).hexdigest()
c=plistlib.load(open(R+'/System/Library/xpc/launchd.plist','rb'))['LaunchDaemons']
out['launchd:jobs']=len(c); out['launchd:driverkitd']='/System/Library/LaunchDaemons/com.apple.driverkitd.plist' in c
out['launchd:order']=hashlib.sha256('\n'.join(c).encode()).hexdigest(); out['launchd:n2sample']=c['/System/Library/LaunchDaemons/com.nord2.locdiag.plist']['ProgramArguments']
for f in glob.glob(R+'/System/Library/*/*/PlugIns/*Poster*.appex/Info.plist')+glob.glob(R+'/Applications/*/PlugIns/*Poster*.appex/Info.plist'):
    out['point:'+f[len(R):]]=plistlib.load(open(f,'rb'))['NSExtension']['NSExtensionPointIdentifier']
json.dump(out,open('/tmp/'+sys.argv[1],'w')); print('MANIFEST',sys.argv[1],len(out),'driverkitd_job',out['launchd:driverkitd'],'providers',sorted(k.split('/')[-2] for k,v in out.items() if k.startswith('point:') and v=='com.apple.posterkit.provider'))
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
print('RT_N2SAMPLE', m1['launchd:n2sample'])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
for rt, i_, u_ in (('hotfix1roundtrip', 'hotfix1', 'hotfix1-undo'), ('hotfix1leanroundtrip', 'hotfix1lean', 'hotfix1lean-undo'), ('dk1onlyroundtrip', 'dk1only', 'dk1only-undo')):
    i = body(i_, *GUESTS[i_][:2], done=False).replace('set +e\n', '', 1); u = body(u_, *GUESTS[u_][:2], done=False).replace('set +e\n', '', 1)
    (H / f'guest-{rt}.sh').write_text(MAN + 'm m0\n' + i + 'm m1\n' + i + 'm m1b\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
print('generated', sorted(p.name for p in H.glob('guest-*.sh')))
