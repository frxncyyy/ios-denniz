#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of heat-20261114 (run on the host, writes only here).
heat1     = dasdmod1 (the stored 1970 lastModulation out of dasd's widget budget preferences; needs kernel 0530 = image q10jck or later)
heat1full = dasdmod1 + respawn1 (OPTIONAL: bluetoothd / fairplayd.H2 / wifip2pd jobs out of the launchd cache: the 10 s respawn loops)
the -undo guests run the blocks in reverse order; the *roundtrip guests do install, install again, undo, undo again with manifests."""
import hashlib, json
from pathlib import Path
H = Path(__file__).resolve().parent
blocks = {n: (H / f'block-{n}.py').read_text() for n in ('dasdmod1', 'respawn1')}
HEAD = 'set +e\n# %s (generated by heat-20261114/make_guests.py from block-*.py; see those files for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def body(name, parts, done=True):
    s = HEAD % name
    for b, undo in parts:
        s += "python3 - <<'GUEST'\nUNDO=%s\n%sGUEST\n" % (undo, blocks[b])
    t = TAIL % (name, 'metal receipt launchd sha' if any(b == 'respawn1' for b, _ in parts) else 'unchanged')
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
GUESTS = {'heat1': ([('dasdmod1', False)], 'dasd widget budgets: stored 1970 lastModulation removed'),
          'heat1-undo': ([('dasdmod1', True)], 'undo of heat1'),
          'heat1full': ([('dasdmod1', False), ('respawn1', False)], 'heat1 + bluetoothd / fairplayd.H2 / wifip2pd launchd jobs removed (optional)'),
          'heat1full-undo': ([('respawn1', True), ('dasdmod1', True)], 'undo of heat1full')}
for name, (parts, purpose) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': name, 'blocks': [b for b, _ in parts], 'blocks_sha256': {k: hashlib.sha256(v.encode()).hexdigest() for k, v in blocks.items()}}, indent=1, sort_keys=True) + '\n')
MAN = r'''set +e
mkdir -p /tmp
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,plistlib
R='/work/root'; out={}
for top in ['/private/var/db/nord2-stock','/private/var/mobile/Library/Preferences','/private/var/root/Library/Preferences','/System/Library/xpc','/private/var/db/nord2-metal']:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p) and not os.path.islink(p) and (st.st_size<4<<20): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
c=plistlib.load(open(R+'/System/Library/xpc/launchd.plist','rb'))['LaunchDaemons']
out['launchd:jobs']=len(c); out['launchd:order']=hashlib.sha256('\n'.join(c).encode()).hexdigest()
out['launchd:loops']=[('/System/Library/LaunchDaemons/com.apple.%s.plist'%n) in c for n in ('bluetoothd','fairplayd.H2','wifip2pd')]
out['launchd:metal']=json.load(open(R+'/private/var/db/nord2-metal/receipt.json')).get('installed_launchd_sha256')==hashlib.sha256(open(R+'/System/Library/xpc/launchd.plist','rb').read()).hexdigest()
d=plistlib.load(open(R+'/private/var/mobile/Library/Preferences/com.apple.dasd.widgetRefreshBudgets.plist','rb'))
out['dasd:lastModulation']=repr(d.get('lastModulation','absent')); out['dasd:others']=hashlib.sha256(repr(sorted((k,repr(v)) for k,v in d.items() if k!='lastModulation')).encode()).hexdigest()
json.dump(out,open('/tmp/'+sys.argv[1],'w')); print('MANIFEST',sys.argv[1],len(out),'lastModulation',out['dasd:lastModulation'],'loop jobs present',out['launchd:loops'],'jobs',out['launchd:jobs'],'launchd==metal receipt',out['launchd:metal'])
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
print('RT_INSTALL_DASD', m0['dasd:lastModulation'], '->', m1['dasd:lastModulation'], 'other keys unchanged', m0['dasd:others']==m1['dasd:others'])
print('RT_INSTALL_LAUNCHD jobs', m0['launchd:jobs'], '->', m1['launchd:jobs'], 'loop jobs', m0['launchd:loops'], '->', m1['launchd:loops'], 'metal receipt matches', m1['launchd:metal'])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
for rt, inst, undo in (('heat1roundtrip', 'heat1', 'heat1-undo'), ('heat1fullroundtrip', 'heat1full', 'heat1full-undo')):
    i = body(inst, GUESTS[inst][0], done=False).replace('set +e\n', '', 1); u = body(undo, GUESTS[undo][0], done=False).replace('set +e\n', '', 1)
    (H / f'guest-{rt}.sh').write_text(MAN + 'm m0\n' + i + 'm m1\n' + i + 'm m1b\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
DP = '/private/var/mobile/Library/Preferences/com.apple.dasd.widgetRefreshBudgets.plist'
(H / 'owned-heat1.json').write_text(json.dumps([DP, '/private/var/db/nord2-stock', '/private/var/db/nord2-stock/dasdmod1.json'], indent=0) + '\n')
(H / 'owned-heat1full.json').write_text(json.dumps([DP, '/private/var/db/nord2-stock', '/private/var/db/nord2-stock/dasdmod1.json', '/private/var/db/nord2-stock/respawn1.json',
    '/System/Library/xpc/launchd.plist', '/private/var/db/nord2-metal/receipt.json'], indent=0) + '\n')
(H / 'rehearsal-snapshot.json').write_text(json.dumps({'format': 'nord2-fastroot-1', 'kind': 'snapshot', 'rehearsal_only': True,
    'mirror': str(H.parent / 'mirror/rootfs-mirror.img'), 'bytes': 17179869184,
    'root': json.loads((H.parent / 'mirror/rootfs-mirror.img.manifest.json').read_text())['root'], 'per_chunk_manifest_matches': True, 'phone_partition_writes': 0}, indent=1) + '\n')
print('generated', sorted(p.name for p in H.glob('guest-*.sh')))
