#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of bltorch-20261114 (run on the host, writes only here).
bltorch1 = flash1 (MobileGestalt cached camera-flash -> true: Control Center flashlight) + bright1 (BKEnableALS false, defensive)
flash1   = flash1 alone
the -undo guests run the blocks in reverse order; the *roundtrip guests do install, install again, undo, undo again with manifests."""
import hashlib, json
from pathlib import Path
H = Path(__file__).resolve().parent
blocks = {n: (H / f'block-{n}.py').read_text() for n in ('flash1', 'bright1')}
HEAD = 'set +e\n# %s (generated by bltorch-20261114/make_guests.py from block-*.py; see those files for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def body(name, parts, done=True):
    s = HEAD % name
    for b, undo in parts:
        s += "python3 - <<'GUEST'\nUNDO=%s\n%sGUEST\n" % (undo, blocks[b])
    t = TAIL % (name, 'unchanged')
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
GUESTS = {'bltorch1': ([('flash1', False), ('bright1', False)], 'camera-flash cached true (flashlight in Control Center) + BKEnableALS false'),
          'bltorch1-undo': ([('bright1', True), ('flash1', True)], 'undo of bltorch1'),
          'flash1': ([('flash1', False)], 'camera-flash cached true (flashlight in Control Center)'),
          'flash1-undo': ([('flash1', True)], 'undo of flash1')}
for name, (parts, purpose) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': name, 'blocks': [b for b, _ in parts], 'blocks_sha256': {k: hashlib.sha256(v.encode()).hexdigest() for k, v in blocks.items()}}, indent=1, sort_keys=True) + '\n')
MAN = r'''set +e
mkdir -p /tmp
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,plistlib
R='/work/root'; out={}
MGD='/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches'
for top in ['/private/var/db/nord2-stock',MGD,'/private/var/mobile/Library/Preferences','/private/var/root/Library/Preferences','/private/var/mobile/Library/ControlCenter']:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p) and not os.path.islink(p) and (st.st_size<4<<20): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
out['sha:metal-receipt']=hashlib.sha256(open(R+'/private/var/db/nord2-metal/receipt.json','rb').read()).hexdigest()
out['sha:launchd']=hashlib.sha256(open(R+'/System/Library/xpc/launchd.plist','rb').read()).hexdigest()
c=plistlib.load(open(R+MGD+'/com.apple.MobileGestalt.plist','rb'))['CacheData']
out['mg:camera-flash']=[c[0x1290+0x3f],c[0x3f*8]]; out['mg:others']=hashlib.sha256(c[:0x3f*8]+c[0x3f*8+1:]).hexdigest()
b=plistlib.load(open(R+'/private/var/mobile/Library/Preferences/com.apple.backboardd.plist','rb'))
out['bb:BKEnableALS']=repr(b.get('BKEnableALS','absent')); out['bb:others']=hashlib.sha256(repr(sorted((k,repr(v)) for k,v in b.items() if k!='BKEnableALS')).encode()).hexdigest()
json.dump(out,open('/tmp/'+sys.argv[1],'w')); print('MANIFEST',sys.argv[1],len(out),'camera-flash [valid,value]',out['mg:camera-flash'],'BKEnableALS',out['bb:BKEnableALS'])
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
print('RT_INSTALL_MG', m0['mg:camera-flash'], '->', m1['mg:camera-flash'], 'other slots unchanged', m0['mg:others']==m1['mg:others'])
print('RT_INSTALL_BB', m0['bb:BKEnableALS'], '->', m1['bb:BKEnableALS'], 'other keys unchanged', m0['bb:others']==m1['bb:others'])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
for rt, inst, undo in (('bltorch1roundtrip', 'bltorch1', 'bltorch1-undo'), ('flash1roundtrip', 'flash1', 'flash1-undo')):
    i = body(inst, GUESTS[inst][0], done=False).replace('set +e\n', '', 1); u = body(undo, GUESTS[undo][0], done=False).replace('set +e\n', '', 1)
    (H / f'guest-{rt}.sh').write_text(MAN + 'm m0\n' + i + 'm m1\n' + i + 'm m1b\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
MG = '/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches/com.apple.MobileGestalt.plist'
(H / 'owned-bltorch1.json').write_text(json.dumps([MG, '/private/var/mobile/Library/Preferences/com.apple.backboardd.plist', '/private/var/db/nord2-stock',
    '/private/var/db/nord2-stock/flash1.json', '/private/var/db/nord2-stock/bright1.json'], indent=0) + '\n')
(H / 'rehearsal-snapshot.json').write_text(json.dumps({'format': 'nord2-fastroot-1', 'kind': 'snapshot', 'rehearsal_only': True,
    'mirror': str(H.parent / 'mirror/rootfs-mirror.img'), 'bytes': 17179869184,
    'root': json.loads((H.parent / 'mirror/rootfs-mirror.img.manifest.json').read_text())['root'], 'per_chunk_manifest_matches': True, 'phone_partition_writes': 0}, indent=1) + '\n')
print('generated', sorted(p.name for p in H.glob('guest-*.sh')))
