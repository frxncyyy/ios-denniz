#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of wallpaper-20261114 (run on the host, writes only here).
wallpaper1 = block-wallpaper1.py alone; stockwall = stock1 + poster1 (blocks of ../stock-20261114, unchanged) + wallpaper1 in ONE VM run;
the undo guests run the blocks in reverse order; stockwallroundtrip = install, install again, undo, undo again with tree manifests."""
import hashlib, json
from pathlib import Path
H = Path(__file__).resolve().parent; S = H.parent / 'stock-20261114'
blocks = {'stock1': (S / 'block-stock1.py').read_text(), 'poster1': (S / 'block-poster1.py').read_text(), 'wallpaper1': (H / 'block-wallpaper1.py').read_text()}
APPS = json.loads((S / 'payload-stockall/plan.json').read_text())['stock1']
HEAD = 'set +e\n# %s (generated by wallpaper-20261114/make_guests.py from block-*.py; see those files for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def body(name, parts, receipt, done=True):
    s = HEAD % name
    for b, undo in parts:
        s += "python3 - <<'GUEST'\nUNDO=%s\n%sGUEST\n" % (undo, blocks[b])
    t = TAIL % (name, receipt)
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
GUESTS = {'wallpaper1': ([('wallpaper1', False)], 'unchanged', 'extension points for posters/widgets: feature flag + .appexpt + LS caches aside'),
          'wallpaper1-undo': ([('wallpaper1', True)], 'unchanged', 'undo of wallpaper1'),
          'stockwall': ([('stock1', False), ('poster1', False), ('wallpaper1', False)], 'metal receipt launchd sha', 'stock1 + poster1 + wallpaper1 in one VM run'),
          'stockwall-undo': ([('wallpaper1', True), ('poster1', True), ('stock1', True)], 'metal receipt launchd sha', 'wallpaper1 undo + poster1 undo + stock1 undo')}
for name, (parts, receipt, purpose) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts, receipt))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'stock1': APPS, 'blocks_sha256': {k: hashlib.sha256(v.encode()).hexdigest() for k, v in blocks.items()}}, indent=1, sort_keys=True) + '\n')
MAN = r'''set +e
mkdir -p /tmp
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,glob
R='/work/root'; out={}
for top in ['/Applications','/private/var/staged_system_apps','/private/var/mobile/Library/Application Support','/private/var/db/nord2-stock',
            '/System/Library/ExtensionKit','/System/Library/FeatureFlags']+[p[len(R):] for p in glob.glob(R+'/private/var/mobile/Containers/Data/Application/*') if os.path.exists(p+'/.com.apple.mobile_container_manager.metadata.plist') and b'com.apple.PosterBoard' in open(p+'/.com.apple.mobile_container_manager.metadata.plist','rb').read()]:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
for f in ['/System/Library/xpc/launchd.plist','/System/Library/xpc/extensions.plist','/private/var/db/nord2-metal/receipt.json','/System/Library/FeatureFlags/Domain/ExtensionKit.plist']+sorted(p[len(R):] for p in glob.glob(R+'/System/Library/ExtensionKit/ExtensionPoints/*')):
    out['sha:'+f]=hashlib.sha256(open(R+f,'rb').read()).hexdigest()
json.dump(out,open('/tmp/'+sys.argv[1],'w')); print('MANIFEST',sys.argv[1],len(out))
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch)); print('RT_INSTALL_CHANGED_SYSTEM', [k for k in ch if 'System/Library' in k or 'wallpaper1' in k])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
for rt, inst, undo in (('stockwallroundtrip', 'stockwall', 'stockwall-undo'), ('wallpaper1roundtrip', 'wallpaper1', 'wallpaper1-undo')):
    i = body(inst, *GUESTS[inst][:2], done=False).replace('set +e\n', '', 1); u = body(undo, *GUESTS[undo][:2], done=False).replace('set +e\n', '', 1)
    (H / f'guest-{rt}.sh').write_text(MAN + 'm m0\n' + i + 'm m1\n' + i + 'm m1b\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
print('generated', sorted(p.name for p in H.glob('guest-*.sh')))
