#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of stock-20261114 from block-stock1.py / block-poster1.py (run on the host, writes only here)."""
import json
from pathlib import Path
H = Path(__file__).resolve().parent
APPS = {'AppleTV.app': 'com.apple.tv', 'Books.app': 'com.apple.iBooks', 'Bridge.app': 'com.apple.Bridge', 'Calculator.app': 'com.apple.calculator',
        'Compass.app': 'com.apple.compass', 'Contacts.app': 'com.apple.MobileAddressBook', 'FaceTime.app': 'com.apple.facetime',
        'Files.app': 'com.apple.DocumentsApp', 'FindMy.app': 'com.apple.findmy', 'Fitness.app': 'com.apple.Fitness', 'Freeform.app': 'com.apple.freeform',
        'Health.app': 'com.apple.Health', 'Home.app': 'com.apple.Home', 'Magnifier.app': 'com.apple.Magnifier', 'Maps.app': 'com.apple.Maps',
        'Measure.app': 'com.apple.measure', 'MobileCal.app': 'com.apple.mobilecal', 'MobileMail.app': 'com.apple.mobilemail',
        'MobileNotes.app': 'com.apple.mobilenotes', 'MobileStore.app': 'com.apple.MobileStore', 'MobileTimer.app': 'com.apple.mobiletimer',
        'Music.app': 'com.apple.Music', 'News.app': 'com.apple.news', 'Passbook.app': 'com.apple.Passbook', 'Podcasts.app': 'com.apple.podcasts',
        'Reminders.app': 'com.apple.reminders', 'SequoiaTranslator.app': 'com.apple.Translate', 'Shortcuts.app': 'com.apple.shortcuts',
        'Stocks.app': 'com.apple.stocks', 'Tips.app': 'com.apple.tips', 'VoiceMemos.app': 'com.apple.VoiceMemos', 'Weather.app': 'com.apple.weather'}
blocks = {'stock1': (H / 'block-stock1.py').read_text(), 'poster1': (H / 'block-poster1.py').read_text()}
HEAD = 'set +e\n# %s (generated by make_guests.py from block-*.py; see those files for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def guest(name, parts, receipt):
    s = HEAD % name
    for b, undo in parts:
        s += "python3 - <<'GUEST'\nUNDO=%s\n%sGUEST\n" % (undo, blocks[b])
    s += TAIL % (name, receipt)
    (H / f'guest-{name}.sh').write_text(s)
guest('stock1', [('stock1', False)], 'unchanged')
guest('stock1-undo', [('stock1', True)], 'unchanged')
guest('poster1', [('poster1', False)], 'metal receipt launchd sha')
guest('poster1-undo', [('poster1', True)], 'metal receipt launchd sha')
guest('stockall', [('stock1', False), ('poster1', False)], 'metal receipt launchd sha')
guest('stockall-undo', [('poster1', True), ('stock1', True)], 'metal receipt launchd sha')
for name, purpose in [('stock1', 'move the 32 staged removable stock apps to /Applications + LS caches aside'),
                      ('stock1-undo', 'undo of stock1'), ('poster1', 'PosterBoard HOME = its data container; old data store kept aside'),
                      ('poster1-undo', 'undo of poster1'), ('stockall', 'stock1 + poster1 in one VM run'), ('stockall-undo', 'poster1 undo + stock1 undo')]:
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'stock1': {'apps': APPS}}, indent=1, sort_keys=True) + '\n')
print('generated')
