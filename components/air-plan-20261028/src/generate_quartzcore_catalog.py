#!/usr/bin/env python3
"""Generate an identity-pinned exact QuartzCore render-pipeline catalog."""
import argparse
import ctypes as C
import hashlib
import json
from pathlib import Path
import subprocess
import sys


class Blob(C.Structure):
    _fields_ = [('bytes', C.c_void_p), ('length', C.c_size_t)]


class Attachment(C.Structure):
    _fields_ = [('format', C.c_uint32), ('write_mask', C.c_uint32)]


class Attribute(C.Structure):
    _fields_ = [(name, C.c_uint32) for name in ('index', 'format', 'offset', 'buffer_index')]


class Layout(C.Structure):
    _fields_ = [(name, C.c_uint32) for name in ('index', 'stride', 'step_function', 'step_rate')]


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read_json(path):
    with path.open('r', encoding='utf-8') as source:
        return json.load(source)


def configure(lib):
    lib.tegu_air_library_open.argtypes = [C.c_void_p, C.c_size_t, C.c_void_p, C.c_size_t]
    lib.tegu_air_library_open.restype = C.c_void_p
    lib.tegu_air_library_close.argtypes = [C.c_void_p]
    lib.tegu_air_function_count.argtypes = [C.c_void_p]
    lib.tegu_air_function_count.restype = C.c_size_t
    lib.tegu_air_function_info.argtypes = [C.c_void_p, C.c_size_t, C.c_void_p, C.c_size_t, C.POINTER(C.c_uint32)]
    lib.tegu_air_function_info.restype = C.c_size_t
    lib.tegu_air_render_pipeline_create_with_attachments.argtypes = [
        C.c_void_p, C.c_void_p, C.c_size_t, C.c_void_p, C.c_void_p, C.c_size_t,
        C.POINTER(Attachment), C.c_size_t, C.POINTER(Attribute), C.c_size_t,
        C.POINTER(Layout), C.c_size_t, C.c_void_p, C.c_size_t,
        C.POINTER(Blob), C.POINTER(Blob), C.POINTER(Blob), C.c_void_p, C.c_size_t]
    lib.tegu_air_render_pipeline_create_with_attachments.restype = C.c_void_p
    lib.tegu_air_render_pipeline_close.argtypes = [C.c_void_p]
    lib.tegu_air_blob_free.argtypes = [C.POINTER(Blob)]


def function_inventory(lib, library):
    rows = []
    for index in range(lib.tegu_air_function_count(library)):
        kind = C.c_uint32()
        needed = lib.tegu_air_function_info(library, index, None, 0, C.byref(kind))
        if needed < 2 or needed > 4096:
            raise RuntimeError(f'invalid function name length at index {index}: {needed}')
        name = C.create_string_buffer(needed)
        if lib.tegu_air_function_info(library, index, name, needed, C.byref(kind)) != needed:
            raise RuntimeError(f'unstable function record at index {index}')
        rows.append({'name': name.value.decode('utf-8'), 'type': kind.value})
    return rows


def c_string(value):
    return json.dumps(value, ensure_ascii=True)


def validate_descriptor(name, descriptor, parser):
    scalar = {
        'raster_sample_count', 'depth_attachment_pixel_format', 'stencil_attachment_pixel_format',
        'alpha_to_coverage_enabled', 'alpha_to_one_enabled', 'rasterization_enabled',
        'input_primitive_topology', 'max_vertex_amplification_count',
        'support_indirect_command_buffers', 'attachments', 'attributes', 'layouts'}
    if set(descriptor) != scalar:
        parser.error(f'descriptor {name} has incomplete or unknown fields: {sorted(set(descriptor) ^ scalar)}')
    if len(descriptor['attachments']) != 8:
        parser.error(f'descriptor {name} must contain all eight attachment slots')
    blend_fields = {'enabled', 'rgb_op', 'rgb_src', 'rgb_dst', 'alpha_op', 'alpha_src', 'alpha_dst'}
    for index, attachment in enumerate(descriptor['attachments']):
        if set(attachment) != {'format', 'write_mask', 'blend'} or set(attachment['blend']) != blend_fields:
            parser.error(f'descriptor {name} attachment {index} is incomplete')
    attribute_fields = {'index', 'format', 'offset', 'buffer_index'}
    layout_fields = {'index', 'stride', 'step_function', 'step_rate'}
    if any(set(row) != attribute_fields for row in descriptor['attributes']):
        parser.error(f'descriptor {name} has an incomplete attribute')
    if any(set(row) != layout_fields for row in descriptor['layouts']):
        parser.error(f'descriptor {name} has an incomplete layout')
    attribute_indices = [row['index'] for row in descriptor['attributes']]
    layout_indices = [row['index'] for row in descriptor['layouts']]
    if len(set(attribute_indices)) != len(attribute_indices) or any(index not in range(31) for index in attribute_indices):
        parser.error(f'descriptor {name} has duplicate or out-of-range attributes')
    if len(set(layout_indices)) != len(layout_indices) or any(index not in range(31) for index in layout_indices):
        parser.error(f'descriptor {name} has duplicate or out-of-range layouts')


def render_header(catalog):
    lines = [
        '/* Generated by generate_quartzcore_catalog.py; do not edit. */',
        '#ifndef TEGU_QUARTZCORE_PIPELINE_CATALOG_H',
        '#define TEGU_QUARTZCORE_PIPELINE_CATALOG_H',
        '#include <stdint.h>',
        'static inline int tegu_qc_streq(const char *a,const char *b) {',
        ' if(!a||!b){return 0;} while(*a&&*a==*b){a++;b++;} return *a==*b;',
        '}',
        'struct tegu_qc_catalog_blend { uint32_t enabled,rgb_op,rgb_src,rgb_dst,alpha_op,alpha_src,alpha_dst; };',
        'struct tegu_qc_catalog_attachment { uint32_t format,write_mask; struct tegu_qc_catalog_blend blend; };',
        'struct tegu_qc_catalog_attribute { uint32_t index,format,offset,buffer_index; };',
        'struct tegu_qc_catalog_layout { uint32_t index,stride,step_function,step_rate; };',
        'struct tegu_qc_catalog_descriptor { const char *name; uint32_t raster_sample_count,depth_format,stencil_format,alpha_to_coverage,alpha_to_one,rasterization,input_topology,max_vertex_amplification,indirect_commands; struct tegu_qc_catalog_attachment attachments[8]; struct tegu_qc_catalog_attribute attributes[31]; uint32_t attribute_count; struct tegu_qc_catalog_layout layouts[31]; uint32_t layout_count; };',
        'struct tegu_qc_catalog_entry { const char *key_sha256,*vertex,*fragment,*descriptor_class,*metadata_sha256,*vertex_spirv_sha256,*fragment_spirv_sha256; uint32_t vertex_spirv_bytes,fragment_spirv_bytes,metadata_bytes; };',
        f'static const char tegu_qc_catalog_sha256[]={c_string(catalog["catalog_sha256"])};',
        f'static const char tegu_qc_catalog_donor_sha256[]={c_string(catalog["inputs"]["donor_sha256"])};',
        f'static const char tegu_qc_catalog_profile_sha256[]={c_string(catalog["inputs"]["profile_sha256"])};',
        f'static const char tegu_qc_catalog_translator_commit[]={c_string(catalog["inputs"]["translator_commit"])};',
        'static const struct tegu_qc_catalog_descriptor tegu_qc_catalog_descriptors[]={',
    ]
    for name, d in catalog['descriptor_classes'].items():
        attachments = []
        for a in d['attachments']:
            b = a['blend']
            attachments.append('{{{},{},{{{},{},{},{},{},{},{}}}}}'.format(
                a['format'], a['write_mask'], int(b['enabled']), b['rgb_op'], b['rgb_src'], b['rgb_dst'],
                b['alpha_op'], b['alpha_src'], b['alpha_dst']))
        attributes = ['{{{},{},{},{}}}'.format(a['index'], a['format'], a['offset'], a['buffer_index']) for a in d['attributes']]
        layouts = ['{{{},{},{},{}}}'.format(x['index'], x['stride'], x['step_function'], x['step_rate']) for x in d['layouts']]
        lines.append('{{{},{},{},{},{},{},{},{},{},{},{{{}}},{{{}}},{},{{{}}},{}}},'.format(
            c_string(name), d['raster_sample_count'], d['depth_attachment_pixel_format'], d['stencil_attachment_pixel_format'],
            int(d['alpha_to_coverage_enabled']), int(d['alpha_to_one_enabled']), int(d['rasterization_enabled']),
            d['input_primitive_topology'], d['max_vertex_amplification_count'], int(d['support_indirect_command_buffers']),
            ','.join(attachments), ','.join(attributes), len(attributes), ','.join(layouts), len(layouts)))
    lines.extend(['};', 'static const struct tegu_qc_catalog_entry tegu_qc_catalog_entries[]={'])
    for e in catalog['entries']:
        lines.append('{{{},{},{},{},{},{},{},{},{},{}}},'.format(
            *(c_string(e[k]) for k in ('key_sha256', 'vertex', 'fragment', 'descriptor_class',
                                       'metadata_sha256', 'vertex_spirv_sha256', 'fragment_spirv_sha256')),
            e['vertex_spirv_bytes'], e['fragment_spirv_bytes'], e['metadata_bytes']))
    lines.extend([
        '};',
        '#define TEGU_QC_CATALOG_DESCRIPTOR_COUNT ((uint32_t)(sizeof(tegu_qc_catalog_descriptors)/sizeof(tegu_qc_catalog_descriptors[0])))',
        '#define TEGU_QC_CATALOG_ENTRY_COUNT ((uint32_t)(sizeof(tegu_qc_catalog_entries)/sizeof(tegu_qc_catalog_entries[0])))',
        'static inline const struct tegu_qc_catalog_entry *tegu_qc_catalog_find_names(const char *vertex,const char *fragment) {',
        ' if(!vertex||!fragment){return 0;} for(uint32_t i=0;i<TEGU_QC_CATALOG_ENTRY_COUNT;i++){if(tegu_qc_streq(vertex,tegu_qc_catalog_entries[i].vertex)&&tegu_qc_streq(fragment,tegu_qc_catalog_entries[i].fragment))return &tegu_qc_catalog_entries[i];} return 0;',
        '}',
        'static inline const struct tegu_qc_catalog_descriptor *tegu_qc_catalog_entry_descriptor(const struct tegu_qc_catalog_entry *entry) {',
        ' if(!entry){return 0;} for(uint32_t i=0;i<TEGU_QC_CATALOG_DESCRIPTOR_COUNT;i++){if(tegu_qc_streq(entry->descriptor_class,tegu_qc_catalog_descriptors[i].name))return &tegu_qc_catalog_descriptors[i];} return 0;',
        '}',
        'static inline int tegu_qc_catalog_descriptor_equal(const struct tegu_qc_catalog_descriptor *a,const struct tegu_qc_catalog_descriptor *b) {',
        ' if(!a||!b||a->raster_sample_count!=b->raster_sample_count||a->depth_format!=b->depth_format||a->stencil_format!=b->stencil_format||a->alpha_to_coverage!=b->alpha_to_coverage||a->alpha_to_one!=b->alpha_to_one||a->rasterization!=b->rasterization||a->input_topology!=b->input_topology||a->max_vertex_amplification!=b->max_vertex_amplification||a->indirect_commands!=b->indirect_commands||a->attribute_count!=b->attribute_count||a->layout_count!=b->layout_count)return 0;',
        ' for(uint32_t i=0;i<8;i++){const struct tegu_qc_catalog_attachment *x=&a->attachments[i],*y=&b->attachments[i];if(x->format!=y->format||x->write_mask!=y->write_mask||x->blend.enabled!=y->blend.enabled||x->blend.rgb_op!=y->blend.rgb_op||x->blend.rgb_src!=y->blend.rgb_src||x->blend.rgb_dst!=y->blend.rgb_dst||x->blend.alpha_op!=y->blend.alpha_op||x->blend.alpha_src!=y->blend.alpha_src||x->blend.alpha_dst!=y->blend.alpha_dst)return 0;}',
        ' for(uint32_t i=0;i<a->attribute_count;i++){const struct tegu_qc_catalog_attribute *x=&a->attributes[i],*y=&b->attributes[i];if(x->index!=y->index||x->format!=y->format||x->offset!=y->offset||x->buffer_index!=y->buffer_index)return 0;}',
        ' for(uint32_t i=0;i<a->layout_count;i++){const struct tegu_qc_catalog_layout *x=&a->layouts[i],*y=&b->layouts[i];if(x->index!=y->index||x->stride!=y->stride||x->step_function!=y->step_function||x->step_rate!=y->step_rate)return 0;} return 1;',
        '}',
        'static inline const struct tegu_qc_catalog_entry *tegu_qc_catalog_find(const char *vertex,const char *fragment,const struct tegu_qc_catalog_descriptor *descriptor) {',
        ' if(!vertex||!fragment||!descriptor){return 0;} for(uint32_t i=0;i<TEGU_QC_CATALOG_ENTRY_COUNT;i++){const struct tegu_qc_catalog_entry *entry=&tegu_qc_catalog_entries[i];if(!tegu_qc_streq(vertex,entry->vertex)||!tegu_qc_streq(fragment,entry->fragment))continue;const struct tegu_qc_catalog_descriptor *expected=tegu_qc_catalog_entry_descriptor(entry);if(tegu_qc_catalog_descriptor_equal(descriptor,expected))return entry;} return 0;',
        '}',
        '#endif', ''
    ])
    return '\n'.join(lines).encode()


def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bridge', type=Path, required=True)
    parser.add_argument('--translator', type=Path, required=True)
    parser.add_argument('--donor', type=Path, required=True)
    parser.add_argument('--profile', type=Path, required=True)
    parser.add_argument('--recipes', type=Path, default=here / 'quartzcore_catalog_recipes.json')
    parser.add_argument('--out-json', type=Path, default=here / 'quartzcore_pipeline_catalog.json')
    parser.add_argument('--out-header', type=Path, default=here / 'quartzcore_pipeline_catalog.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    recipes = read_json(args.recipes)
    if recipes.get('schema') != 1:
        parser.error('unsupported recipe schema')
    for name, descriptor in recipes.get('descriptor_classes', {}).items():
        validate_descriptor(name, descriptor, parser)
    donor, profile = args.donor.read_bytes(), args.profile.read_bytes()
    actual_inputs = {
        'donor_sha256': digest(donor),
        'profile_sha256': digest(profile),
        'translator_commit': subprocess.check_output(
            ['git', '-C', str(args.translator), 'rev-parse', 'HEAD'], text=True).strip(),
    }
    for key, actual in actual_inputs.items():
        if recipes['inputs'][key] != actual:
            parser.error(f'{key} differs from recipe: {actual}')

    lib = C.CDLL(str(args.bridge.resolve()))
    configure(lib)
    error = C.create_string_buffer(2048)
    library = lib.tegu_air_library_open(donor, len(donor), error, len(error))
    if not library:
        parser.error('donor parse failed: ' + error.value.decode(errors='replace'))
    try:
        inventory = function_inventory(lib, library)
        counts = {name: sum(row['type'] == kind for row in inventory)
                  for name, kind in [('vertex', 1), ('fragment', 2), ('kernel', 3)]}
        if counts != recipes['inputs']['function_counts']:
            parser.error(f'function inventory differs from recipe: {counts}')
        available = {(row['name'], row['type']) for row in inventory}
        contracts, entries = {}, []
        seen = set()
        for recipe in recipes['entries']:
            vertex, fragment = recipe['vertex'], recipe['fragment']
            if (vertex, 1) not in available or (fragment, 2) not in available:
                parser.error(f'function pair absent or wrong stage: {vertex} + {fragment}')
            descriptor_name = recipe['descriptor_class']
            descriptor = recipes['descriptor_classes'].get(descriptor_name)
            if descriptor is None:
                parser.error(f'unknown descriptor class: {descriptor_name}')
            pair = (vertex, fragment, descriptor_name)
            if pair in seen:
                parser.error(f'duplicate catalog recipe: {pair}')
            seen.add(pair)
            active = [a for a in descriptor['attachments'] if a['format']]
            attachment_array = (Attachment * len(active))(*[Attachment(a['format'], a['write_mask']) for a in active])
            attribute_array = (Attribute * len(descriptor['attributes']))
            attribute_array = attribute_array(*[Attribute(a['index'], a['format'], a['offset'], a['buffer_index']) for a in descriptor['attributes']])
            layout_array = (Layout * len(descriptor['layouts']))
            layout_array = layout_array(*[Layout(x['index'], x['stride'], x['step_function'], x['step_rate']) for x in descriptor['layouts']])
            outputs = [Blob(), Blob(), Blob()]
            error.value = b''
            pipeline = lib.tegu_air_render_pipeline_create_with_attachments(
                library, vertex.encode(), len(vertex), library, fragment.encode(), len(fragment),
                attachment_array, len(active), attribute_array, len(attribute_array), layout_array, len(layout_array),
                profile, len(profile), C.byref(outputs[0]), C.byref(outputs[1]), C.byref(outputs[2]), error, len(error))
            if not pipeline:
                parser.error(f'compile failed for {vertex} + {fragment}: {error.value.decode(errors="replace")}')
            try:
                blobs = [C.string_at(output.bytes, output.length) for output in outputs]
                metadata = json.loads(blobs[2])
                expected = read_json(args.recipes.parent / recipe['contract'])
                if metadata != expected:
                    parser.error(f'metadata differs from exact contract for {vertex} + {fragment}')
                metadata_sha = digest(canonical(metadata))
                contracts.setdefault(metadata_sha, metadata)
                key_value = {
                    'schema': 1,
                    'inputs': actual_inputs,
                    'vertex': vertex,
                    'fragment': fragment,
                    'descriptor': descriptor,
                    'metadata_sha256': metadata_sha,
                }
                entries.append({
                    'key_sha256': digest(canonical(key_value)),
                    'vertex': vertex,
                    'fragment': fragment,
                    'descriptor_class': descriptor_name,
                    'metadata_sha256': metadata_sha,
                    'vertex_spirv_sha256': digest(blobs[0]),
                    'fragment_spirv_sha256': digest(blobs[1]),
                    'vertex_spirv_bytes': len(blobs[0]),
                    'fragment_spirv_bytes': len(blobs[1]),
                    'metadata_bytes': len(blobs[2]),
                })
            finally:
                lib.tegu_air_render_pipeline_close(pipeline)
                for output in outputs:
                    lib.tegu_air_blob_free(C.byref(output))
    finally:
        lib.tegu_air_library_close(library)

    entries.sort(key=lambda row: (row['vertex'], row['fragment'], row['descriptor_class']))
    catalog = {
        'schema': 1,
        'scope': 'exact AIR translation catalog; not native execution approval',
        'inputs': actual_inputs,
        'evidence': recipes.get('evidence', {}),
        'function_inventory': {'counts': counts, 'sha256': digest(canonical(inventory))},
        'descriptor_classes': recipes['descriptor_classes'],
        'contracts': dict(sorted(contracts.items())),
        'entries': entries,
    }
    catalog['catalog_sha256'] = digest(canonical(catalog))
    json_bytes = (json.dumps(catalog, indent=2, sort_keys=True) + '\n').encode()
    header_bytes = render_header(catalog)
    outputs = [(args.out_json, json_bytes), (args.out_header, header_bytes)]
    if args.check:
        bad = [str(path) for path, data in outputs if not path.is_file() or path.read_bytes() != data]
        if bad:
            print('stale generated catalog: ' + ', '.join(bad), file=sys.stderr)
            return 1
    else:
        for path, data in outputs:
            path.write_bytes(data)
    print(json.dumps({'catalog_sha256': catalog['catalog_sha256'], 'entries': len(entries),
                      'contracts': len(contracts), 'function_counts': counts}, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
