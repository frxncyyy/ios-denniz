#!/usr/bin/env python3
"""Host oracle for two distinct source textures through captured QuartzCore AIR."""
import argparse
import hashlib
import json
import math
import struct
from pathlib import Path

ALPHAS=(0,64,128,192,255)
WIDTH=HEIGHT=16
CLEAR=(40,80,120,128)  # RGBA bytes; public target storage is BGRA8.

def half(value):
    return struct.unpack('<e',struct.pack('<e',value))[0]

def source_texel(alpha, snapshot):
    if not isinstance(alpha,int) or alpha<0 or alpha>255: raise ValueError('invalid source alpha')
    if snapshot==0: ratios=(2,4,8)
    elif snapshot==1: ratios=(8,2,4)
    else: raise ValueError('invalid texture snapshot')
    return (alpha//ratios[0],alpha//ratios[1],alpha//ratios[2],alpha)

def filtered_source(alpha,snapshot):
    """Model the captured FS four sequential half FMA quarter-weight taps.

    Each texture is constant, and the captured FS weights are four binary16
    0.25 values. Coordinates therefore do not change the source color, but
    each of the four half-precision accumulation roundings is represented.
    """
    out=[]
    for byte in source_texel(alpha,snapshot):
        texel=half(byte/255.0)
        accum=half(0.0)
        for _ in range(4):
            accum=half(texel*half(0.25)+accum)
        out.append(accum)
    return tuple(out)

def over(source,destination):
    """UNORM8 target source-over, evaluating source floats before store."""
    a=source[3]
    values=tuple(source[i]+(destination[i]/255.0)*(1.0-a) for i in range(3))
    values+=(a+(destination[3]/255.0)*(1.0-a),)
    return tuple(max(0,min(255,math.floor(v*255.0+0.5))) for v in values)

def covered(x,y):
    # Captured PerVertex triangle, expressed as exact pixel-center integer
    # edge tests for the recorded 16x16 target. Its 66-pixel mask is checked
    # against the independent raw gradient oracle by the tests.
    dx=8*x+4-WIDTH;dy=32*y+16-4*HEIGHT
    return dx>=0 and dy>=0 and dx*23*HEIGHT+dy*6*WIDTH<=138*WIDTH*HEIGHT

def frame(alpha):
    beta=255-alpha
    src_a=filtered_source(alpha,0);src_b=filtered_source(beta,1)
    first=over(src_a,CLEAR);second=over(src_b,first)
    out=bytearray();mask=bytearray()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            inside=covered(x,y);rgba=second if inside else CLEAR
            out.extend((rgba[2],rgba[1],rgba[0],rgba[3]))
            mask.append(1 if inside else 0)
    return bytes(out),bytes(mask),source_texel(alpha,0),source_texel(beta,1),CLEAR,first,second

def frame_once(alpha):
    src=filtered_source(alpha,0);one=over(src,CLEAR)
    return bytes(c for y in range(HEIGHT) for x in range(WIDTH) for c in
        ((one[2],one[1],one[0],one[3]) if covered(x,y) else (CLEAR[2],CLEAR[1],CLEAR[0],CLEAR[3])))

def frame_same_source(alpha):
    src=filtered_source(alpha,0);first=over(src,CLEAR);second=over(src,first)
    return bytes(c for y in range(HEIGHT) for x in range(WIDTH) for c in
        ((second[2],second[1],second[0],second[3]) if covered(x,y) else (CLEAR[2],CLEAR[1],CLEAR[0],CLEAR[3])))

def write_header(path,alpha,blob,mask):
    lines=['/* Generated by double_oracle.py; host oracle, not GPU output. */',
           f'#define TEGU_LOAD_SOURCE_ALPHA {alpha}u',
           f'#define TEGU_LOAD_SECOND_SOURCE_ALPHA {255-alpha}u',
           'static const unsigned char tegu_load_expected_bgra8[1024] = {']
    for i in range(0,len(blob),16):lines.append('  '+','.join(f'0x{x:02x}' for x in blob[i:i+16])+',')
    lines+=['};','static const unsigned char tegu_load_covered_pixels[256] = {']
    for i in range(0,len(mask),16):lines.append('  '+','.join(str(x) for x in mask[i:i+16])+',')
    lines+=['};','']
    Path(path).write_text('\n'.join(lines))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--alpha',type=int,choices=ALPHAS,required=True)
    ap.add_argument('--output',type=Path,required=True);ap.add_argument('--header',type=Path,required=True)
    a=ap.parse_args();blob,mask,source_a,source_b,clear,first,second=frame(a.alpha)
    a.output.parent.mkdir(parents=True,exist_ok=True);a.header.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_bytes(blob);write_header(a.header,a.alpha,blob,mask)
    report={'scope':'host-only expected output for actual QuartzCore AIR pair, two distinct texture snapshots',
      'width':WIDTH,'height':HEIGHT,'row_stride':64,'clear_rgba':clear,
      'source_alpha_a':a.alpha,'source_rgba8_a':source_a,'source_alpha_b':255-a.alpha,'source_rgba8_b':source_b,
      'sample_model':'four repeated binary16 quarter-weight accumulations per channel, matching captured FS1 weights',
      'first_draw_rgba_after_blend':first,'second_draw_rgba_after_blend':second,
      'covered_pixels':sum(mask),'clear_pixels':len(mask)-sum(mask),'target_bytes':len(blob),
      'sha256':hashlib.sha256(blob).hexdigest(),
      'limits':'CPU model only; no Metal or GPU execution result'}
    a.output.with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
