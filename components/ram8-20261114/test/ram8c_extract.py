#!/usr/bin/env python3
"""0652 host test helper: pull the REAL n2ram code out of the patched osfmk sources into a host-compilable header (argv[1] = out .h).
Taken verbatim: the n2ram block of arm_vm_init.c (table, validate, index base/top, extra_contains, managed_end, mappable_end), pa_valid()
of pmap_data.h and the pmap_has_managed_page() body of pmap.c.  The XNU types/functions they touch are stubbed by ram8c_host_test.c."""
import re, sys
from pathlib import Path
src = Path(__file__).resolve().parent.parent / 'osfmk/src/osfmk'
a = (src / 'arm64/arm_vm_init.c').read_text()
i = a.index('#ifndef N2RAM_STAGE')
j = a.index('SECURITY_READ_ONLY_LATE(vm_map_address_t) physmap_base')
block = a[i:j]
d = (src / 'arm/pmap/pmap_data.h').read_text()
pv = d[d.index('static inline bool\npa_valid(pmap_paddr_t pa)'):]
pv = pv[:pv.index('\n}\n') + 3]
p = (src / 'arm/pmap/pmap.c').read_text()
hm = p[p.index('boolean_t\npmap_has_managed_page(ppnum_t first, ppnum_t last)'):]
hm = hm[:hm.index('\n}\n') + 3]
Path(sys.argv[1]).write_text('/* generated by ram8c_extract.py from the patched sources -- do not edit */\n' + block + '\n' + pv + '\n' + hm)
print('extracted', len(block), len(pv), len(hm))
