#!/usr/bin/env python3
"""Generates the guest scripts and payload dirs of sbshift-20261114 (host only, writes only here).
sbshift1 = UIKitCore status bar provider byte patch (block-sbshift1.py); sbshift1-undo = its undo; sbshift1roundtrip = install,
install again, undo, undo again with manifests (VM rehearsal only)."""
import hashlib, json
from pathlib import Path
H = Path(__file__).resolve().parent
BLOCK = (H / 'block-sbshift1.py').read_text()
HEAD = 'set +e\n# %s (generated by sbshift-20261114/make_guests.py from block-sbshift1.py; see that file for what and why)\nfsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\n'
TAIL = "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED none (no Metal receipt involved)'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n"
def body(name, undo, done=True):
    s = HEAD % name + "python3 - <<'GUEST'\nUNDO=%s\n%sGUEST\n" % (undo, BLOCK)
    t = TAIL % name
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
for name, undo, purpose in (('sbshift1', False, 'status bar items clear of the punch hole (UIKitCore Split1125 leading offset 36, trailing -25)'),
                            ('sbshift1-undo', True, 'undo of sbshift1 (stock subcache bytes and page hashes)')):
    (H / f'guest-{name}.sh').write_text(body(name, undo))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': f'guest-{name}.sh', 'kernel_image': 'q10jcq (0551: 0550 band rotation off by default)',
        'block_sha256': hashlib.sha256(BLOCK.encode()).hexdigest()}, indent=1, sort_keys=True) + '\n')
OWNED = ['/private/var/db/nord2-stock', '/private/var/db/nord2-stock/sbshift1.json']
for n in ('sbshift1', 'sbshift1-undo'): (H / f'owned-{n}.json').write_text(json.dumps(OWNED, indent=0) + '\n')
MAN = r'''set +e
mkdir -p /tmp
m(){
mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json
R='/work/root'; out={}
for top in ['/private/var/db/nord2-stock']:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
for n in ('dyld_shared_cache_arm64.03','dyld_shared_cache_arm64'):
    p=R+'/System/Library/Caches/com.apple.dyld/'+n; h=hashlib.sha256()
    with open(p,'rb') as f:
        for b in iter(lambda: f.read(1<<22), b''): h.update(b)
    st=os.stat(p); out['dsc:'+n]=[h.hexdigest(),st.st_size,st.st_mode,st.st_uid,st.st_gid,st.st_nlink]
json.dump(out,open('/tmp/'+sys.argv[1],'w')); print('MANIFEST',sys.argv[1],len(out),'sub03',out['dsc:dyld_shared_cache_arm64.03'][0][:12],'nlink',out['dsc:dyld_shared_cache_arm64.03'][5])
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
i = body('sbshift1', False, done=False).replace('set +e\n', '', 1); u = body('sbshift1-undo', True, done=False).replace('set +e\n', '', 1)
(H / 'guest-sbshift1roundtrip.sh').write_text(MAN + 'm m0\n' + i + 'm m1\n' + i + 'm m1b\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
d = H / 'payload-sbshift1roundtrip'; d.mkdir(exist_ok=True); (d / 'plan.json').write_text(json.dumps({'purpose': 'VM rehearsal only'}) + '\n')
print('generated', sorted(p.name for p in H.glob('guest-*.sh')))
