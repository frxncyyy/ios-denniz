/* DATDBG for a level (0..1000), with Android's RAM VBAT compensation and the thermal halving */
static inline uint8_t
n2h_gain_for(uint32_t level, uint32_t vbat_mv, uint32_t therm, const struct n2h_profile *p)
{
#ifdef N2H_FIXED_GAIN
	(void)level; (void)vbat_mv; (void)p;
	return (uint8_t)(therm == 1 ? N2H_FIXED_GAIN / 2u : N2H_FIXED_GAIN);   /* 0618: q10hapd2's good ticks ran at 0x57..0x59 */
#endif
	if (level > 1000) { level = 1000; }
	if (vbat_mv < N2H_VBAT_MIN) { vbat_mv = N2H_VBAT_MIN; }
	if (vbat_mv > N2H_VBAT_MAX) { vbat_mv = N2H_VBAT_MAX; }
	uint32_t g = (uint32_t)p->gain_max * (850u + 150u * level / 1000u) / 1000u;   /* 0614: floor 0.85 (was 0.55) */
	g = g * N2H_VBAT_REFER / vbat_mv;
	if (therm == 1) { g /= 2u; }
	if (g > N2H_GAIN_HW_MAX) { g = N2H_GAIN_HW_MAX; }
	if (g < 8u) { g = 8u; }
	return (uint8_t)g;
}

/* the waveform for an iOS onset's peak */
static inline uint8_t
n2h_wave_for(uint32_t peak, uint32_t *level)
{
	uint32_t l = peak >= N2H_PEAK_FULL ? 1000u : peak * 1000u / N2H_PEAK_FULL;
	*level = l;
	if (peak >= N2H_HEAVY_PEAK) { return N2H_W_HEAVY; }
	return l < N2H_TICK_BELOW ? N2H_W_TICK : N2H_W_CLICK;
}

/*
 * 0613: the RAM click decision for this tick (call only when the motor is idle).  true = play *wave at *gain.
 *  - a new onset: one click (waveform by its peak); an onset older than N2H_CLICK_STALE_US (motor busy) is dropped (skip "stale");
 *  - the same waveform still sounding (iOS continuous event / pattern) and still loud (recent peak >= N2H_TRAIN_REL % of the onset's
 *    peak and >= N2H_TRAIN_MIN_PEAK): one more click every N2H_TRAIN_GAP_MS until N2H_SUSTAIN_MS (Android-style tick train;
 *    CONT drive is left for waveforms longer than that, i.e. the ringer's vibration);
 *  - the same limits as the CONT path (switch, latch, thermal, budget).
 */
#define N2H_TRAIN_GAP_MS        70u
#define N2H_LOOKAHEAD_US        9000ull   /* 0614 */
#define N2H_TRAIN_REL           50u
#define N2H_TRAIN_MIN_PEAK      2048u
static inline bool
n2h_click_take(struct n2h_state *s, struct n2h_stream *t, struct n2h_env *e, const struct n2h_cfg *c, uint64_t now,
    uint32_t vbat_mv, const struct n2h_profile *p, uint8_t *wave, uint8_t *gain, uint32_t *peak_out)
{
	uint64_t onset = e->onset_us, heard = e->heard_us, quiet = e->quiet_us;
	uint32_t peak, level = 0;
	if (!t->ram_ok || s->nseg) { return false; }
	if (onset == 0 || heard < onset) { return false; }
	if (onset != t->click_onset) {
		t->click_onset = onset;
		t->ons_onset = onset; t->ons_clicks = 0; t->ons_cont = 0; t->ons_skip = N2H_SKIP_NONE;
		t->ons_peak_first = e->peak;
		if (!c->mode || s->latched || s->therm >= 2) { t->ons_skip = N2H_SKIP_OFF; return false; }
		if (now < onset || now - onset > N2H_CLICK_STALE_US) { t->stale++; t->ons_skip = N2H_SKIP_STALE; return false; }
		if (s->budget_us <= 0) { s->throttled++; t->ons_skip = N2H_SKIP_BUDGET; return false; }
		peak = (uint32_t)e->peak;
		t->onset_peak = peak;
		/* 0614: the first write of a waveform often holds only its attack (log: "first 1040" of a 10347 waveform -> weak tick);
		 * a soft-looking onset waits until N2H_LOOKAHEAD_US of it were written (one more 5.3 ms write), then decides on the peak */
		if (n2h_wave_for(peak, &level) != N2H_W_CLICK && n2h_wave_for(peak, &level) != N2H_W_HEAVY &&
		    now - onset < N2H_LOOKAHEAD_US && !(quiet > heard)) {
			t->click_onset = 0;            /* not taken yet: the next tick looks again */
			t->lookahead++;
			return false;
		}
	} else {
		/* tick train: same waveform, still sounding, still loud, not yet a CONT-length event */
		if (t->ons_clicks == 0 || t->ons_onset != onset) { return false; }
		if (!(quiet <= heard && now >= heard && now - heard < N2H_ACTIVE_US)) { return false; }
		if (now - onset >= (uint64_t)N2H_SUSTAIN_MS * 1000u || now - t->train_last_us < (uint64_t)N2H_TRAIN_GAP_MS * 1000u) { return false; }
		peak = (uint32_t)e->peak_recent;
		uint64_t need = t->onset_peak * N2H_TRAIN_REL / 100u;
		if (need < N2H_TRAIN_MIN_PEAK) { need = N2H_TRAIN_MIN_PEAK; }
		if (peak < need) { return false; }
		if (!c->mode || s->latched || s->therm >= 2) { return false; }
		if (s->budget_us <= 0) { s->throttled++; return false; }
		t->trains++;
	}
	if (peak <= N2H_SILENT_BELOW) { peak = N2H_SILENT_BELOW + 1; }
	*wave = n2h_wave_for(peak, &level);
	*gain = n2h_gain_for(level, vbat_mv, s->therm, p);
	*peak_out = peak;
	e->peak_recent = 0;
	t->train_last_us = now;
	t->clicks++;
	t->ons_clicks++;
	t->wave_n[*wave]++;
	return true;
}

/* 0613: the path an ended iOS waveform took (counted once, by the owner's per-waveform log); returns a name for the log */
static inline const char *
n2h_path_account(struct n2h_stream *t, uint64_t onset, uint64_t dur_ms)
{
	unsigned b = dur_ms < 30 ? 0 : dur_ms < 60 ? 1 : dur_ms < 120 ? 2 : dur_ms < 300 ? 3 : 4;
	t->dur_hist[b]++;
	bool mine = t->ons_onset == onset;
	if (mine && t->ons_cont) { t->path_cont++; return t->ons_clicks ? "RAM+CONT" : "CONT"; }
	if (mine && t->ons_clicks > 1) { t->path_train++; return "RAM train"; }
	if (mine && t->ons_clicks == 1) { t->path_ram++; return "RAM"; }
	if (mine && t->ons_skip) {
		t->path_skip++;
		return t->ons_skip == N2H_SKIP_STALE ? "skip (motor busy > 80 ms)" : t->ons_skip == N2H_SKIP_BUDGET ? "skip (budget)" :
		    t->ons_skip == N2H_SKIP_TAIL ? "skip (quiet tail)" : "skip (off/thermal/latched)";
	}
	t->path_none++;
	return "none (not seen while idle)";
}

/* zero crossings of a write's samples with a +-N2H_SILENT_BELOW hysteresis (the iOS waveform's frequency, for the log) */
static inline unsigned
n2h_zc_count(const int16_t *s, unsigned n, volatile int64_t *last_sign)
{
	unsigned zc = 0;
	int64_t ls = *last_sign;
	for (unsigned i = 0; i < n; i++) {
		int64_t sg = s[i] > (int32_t)N2H_SILENT_BELOW ? 1 : s[i] < -(int32_t)N2H_SILENT_BELOW ? -1 : 0;
		if (sg != 0) {
			if (ls != 0 && sg != ls) { zc++; }
			ls = sg;
		}
	}
	*last_sign = ls;
	return zc;
}

