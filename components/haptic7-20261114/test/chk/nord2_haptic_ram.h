/* RAMADDR = addr then bursts of the RAMDATA port (RAMINIT must be on: the caller opened it) */
static inline bool
n2h_ram_addr(const struct n2h_bus *b, uint16_t addr)
{
	return addr < N2H_RAM_END && n2h_write(b, N2H_REG_RAMADDRH, (uint8_t)(addr >> 8)) && n2h_write(b, N2H_REG_RAMADDRL, (uint8_t)addr);
}

static inline bool
n2h_ram_write(const struct n2h_bus *b, uint16_t addr, const uint8_t *v, unsigned n)
{
	if (b->wrn == NULL || addr < N2H_RAM_BASE || (uint32_t)addr + n > N2H_RAM_END || !n2h_ram_addr(b, addr)) { return false; }
	for (unsigned i = 0; i < n; i += N2H_BURST_MAX) {
		unsigned k = n - i < N2H_BURST_MAX ? n - i : N2H_BURST_MAX;
		if (!b->wrn(b->ctx, N2H_REG_RAMDATA, v + i, k)) { return false; }
	}
	return true;
}

/* reads back and compares; *bad = first mismatching offset (n = none). false on a bus error. */
static inline bool
n2h_ram_verify(const struct n2h_bus *b, uint16_t addr, const uint8_t *v, unsigned n, unsigned *bad, uint8_t *got)
{
	uint8_t buf[N2H_BURST_MAX];
	*bad = n;
	if (b->rdn == NULL || !n2h_ram_addr(b, addr)) { return false; }
	for (unsigned i = 0; i < n; i += N2H_BURST_MAX) {
		unsigned k = n - i < N2H_BURST_MAX ? n - i : N2H_BURST_MAX;
		if (!b->rdn(b->ctx, N2H_REG_RAMDATA, buf, k)) { return false; }
		for (unsigned j = 0; j < k && *bad == n; j++) {
			if (buf[j] != v[i + j]) { *bad = i + j; *got = buf[j]; }
		}
	}
	return true;
}

