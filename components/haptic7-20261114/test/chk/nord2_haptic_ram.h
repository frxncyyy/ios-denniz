/*
 * nord2_haptic_ram.h -- 0611 (haptic2-20261114): crisp RAM clicks for the AW8697 (included at the end of nord2_haptic.h; pure C,
 * host-tested by test/haptic_test.c against the simulated chip).
 *
 * Why [V phone logs autocycle/runs/f3, vc9p, gr1 with q10jcz]: 0610 turned every iOS haptic into CONT drive: "on (iOS)" ...
 * "stop (iOS silent) after 41..53 ms", then the chip's brake ran 13..31 ms more ("standby N ms after the stop").  CONT mode is
 * a closed loop that ramps the LRA up over several periods and keeps it at resonance: ~8 cycles of 170 Hz = the "mosquito" buzz
 * the user reported.  Android (the same kernel tree, aw8697.c "vibration run in ram mode") plays every effect from the chip's
 * SRAM: short waveforms with the drive and an antiphase brake baked in.  The Android file aw8697_haptic_170.bin is not on the
 * phone nor in the vendor dump, so this file SYNTHESISES the waveforms at boot, at the f0 the chip tracked during the boot pulse
 * (170 Hz on this motor; 1700 dHz when the reading is missing or outside 160..180 Hz) and uploads them over I2C9.
 *
 * RAM format [V aw8697.c aw8697_container_update / aw8697_ram_loaded, haptic_hv.c get_ram_num]: the image is written from
 * BASE_ADDR through the RAMDATA port (RAMINIT on, RAMADDR auto-increments, bursts); byte 0 at the base is a version byte, then
 * one 4-byte entry per waveform {start H, start L, end H, end L} (absolute SRAM addresses; ram_num = (first start - base - 1) / 4),
 * then the waveforms: signed 8-bit samples at 24 kHz with PWMDBG = 24K [V aw8697.c osc calibration: fre_val 2 -> len / 24000].
 * FIFO_AE/AF = base/2 and base - base/4 (aw8697_container_update).  Playback [V aw8697_haptic_play_wav_seq / play_mode RAM]:
 * WAVSEQ1 = waveform, WAVSEQ2 = 0, loops 0, SYSCTRL play mode RAM with the boost BYPASSED (as Android's RAM mode), active, GO;
 * gain = DATDBG (0x80 = unity, Android's AW8697_HAPTIC_RAM_VBAT_COMP_GAIN, scaled by 4400 / VBAT, ceiling 128 x 4400 / 3000).
 * In bypass the bridge output cannot exceed VBAT whatever the gain: the strongest click equals Android's.
 *
 * Waveforms (full scale = VBAT across the 8.3 ohm LRA, as Android): N drive half-cycles of a soft-clipped sine at f0, then M
 * antiphase half-cycles (the brake: at resonance the LRA's velocity is in phase with the drive, so an antiphase drive takes out
 * about the energy the same number of half-cycles put in; the last brake half-cycle is weaker so the motor is not driven back).
 *   tick  (selection, keyboard, soft taps)  1 cycle drive + 0.7 cycle brake  ~11.8 ms
 *   click (most UIKit impacts)              2 cycles      + 1.7               ~23.5 ms
 *   heavy (very loud iOS transients)        3 cycles      + 2.7               ~35 ms
 * Profiles (compile time, N2H_RAM_PROFILE): 0 default; 1 strong (squarer drive, one more drive half-cycle); 2 soft (pure sine,
 * gain 3/4).
 * Vendor waveforms (compile time, N2H_VENDOR_RAM): nord2_haptic_vendor.h, generated by haptic2-20261114/make_vendor_header.py from
 * Android's own aw8697_haptic_170.bin (odm partition), replaces the synthesis: the file's image is uploaded as Android does
 * (its base address, its table) and tick / click / heavy play the vendor waveform indices chosen by the script.
 */
