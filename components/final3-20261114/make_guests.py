#!/usr/bin/env python3
"""Generates the guest scripts, payload dirs and owned lists of final3-20261114 (run on the host, writes only here).
final3      = haptic1    (haptic-20261114/block-haptic1.py: MobileGestalt cached DeviceSupportsHaptics / ClosedLoopHaptics / haptics /
                          VibratorCapability 0 -> 1; needs kernel 0610)
            + hapticpref (haptic-20261114/block-hapticpref.py: com.apple.preferences.sounds effects-haptic = true only if absent)
            + camflashon (camflash-20261114/guest-camflashon.sh heredoc: Camera.app CAMUserPreferenceDesiredFlashMode -> 1 = flash On;
                          needs kernel 0560 + the camflash camera package in the boot image)
final3-undo = the same blocks, reverse order, undo mode.  (api99a is already on the phone: not part of this transaction.)
Block texts are taken verbatim from the source dirs (sha256 recorded in plan.json).  Files touched: MobileGestalt cache (4 haptic slot
bytes; flash1's camera-flash byte stays as it is), com.apple.preferences.sounds.plist, com.apple.camera.plist, receipts haptic1.json /
hapticpref.json / camflashon.json in /private/var/db/nord2-stock.  No overlap between the blocks.
Chaining: every block's output goes to /tmp/final3.out; a block runs only if no earlier block printed *_REFUSED or a Traceback (else
FINAL3_SKIPPED); the guest then prints FINAL3_REFUSED and txn_final3.sh commits nothing.
guest-final3roundtrip.sh = install, install again, undo, undo again with manifests (payload-final3roundtrip: inst/ + undo/)."""
import hashlib, json, os
from pathlib import Path
H = Path(__file__).resolve().parent; BLD = H.parent
def heredoc(p):
    t = p.read_text(); a = t.index("python3 - <<'GUEST'\n") + len("python3 - <<'GUEST'\n"); b = t.index('\nGUEST\n', a)
    assert t.count("<<'GUEST'") == 1; return t[a:b + 1]
SRC = {'haptic1': BLD / 'haptic-20261114/block-haptic1.py', 'hapticpref': BLD / 'haptic-20261114/block-hapticpref.py'}
blocks = {n: p.read_text() for n, p in SRC.items()}
cam = {False: heredoc(BLD / 'camflash-20261114/guest-camflashon.sh'), True: heredoc(BLD / 'camflash-20261114/guest-camflashon-undo.sh')}
assert "UNDO=False;" in cam[False] and "UNDO=True;" in cam[True] and cam[False].replace('UNDO=False;', 'UNDO=True;') == cam[True]
sha = lambda b: hashlib.sha256(b).hexdigest()
HEAD = ('set +e\n# %s (generated by final3-20261114/make_guests.py; blocks verbatim from haptic-20261114, camflash-20261114)\n'
        'fsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\nmkdir -p /tmp; : > /tmp/final3.out\n'
        "blk(){ if grep -aq '_REFUSED\\|Traceback' /tmp/final3.out; then echo \"FINAL3_SKIPPED $1 (an earlier block refused or failed)\"; return 1; fi; echo \"FINAL3_BLOCK $1\"; }\n")
TAIL = ("if grep -aq '_REFUSED\\|Traceback' /tmp/final3.out; then echo 'FINAL3_REFUSED see the lines above: do not commit'; else echo 'FINAL3_OK %s'; fi\n"
        "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED unchanged'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n")
def body(name, parts, done=True):
    s = HEAD % name
    for b, undo in parts:
        code = cam[undo] if b == 'camflashon' else 'UNDO=%s\n%s' % (undo, blocks[b])
        s += "blk %s && python3 - <<'GUEST' 2>&1 | tee -a /tmp/final3.out\n%sGUEST\n" % (b, code)
    t = TAIL % (name, name)
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
ORDER = ['haptic1', 'hapticpref', 'camflashon']
GUESTS = {'final3': ([(b, False) for b in ORDER], 'haptic1 + hapticpref + camflashon (flash On by default)'),
          'final3-undo': ([(b, True) for b in reversed(ORDER)], 'undo of final3 (reverse order)')}
srcsha = {'haptic-20261114/block-haptic1.py': sha(blocks['haptic1'].encode()), 'haptic-20261114/block-hapticpref.py': sha(blocks['hapticpref'].encode()),
          'camflash-20261114/guest-camflashon.sh': sha((BLD / 'camflash-20261114/guest-camflashon.sh').read_bytes()),
          'camflash-20261114/guest-camflashon-undo.sh': sha((BLD / 'camflash-20261114/guest-camflashon-undo.sh').read_bytes())}
for name, (parts, purpose) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    assert sorted(os.listdir(d)) in ([], ['plan.json'])
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': f'guest-{name}.sh', 'order': [b for b, _ in parts], 'sources_sha256': srcsha,
        'kernel_image': 'q10jcz (0610 haptics for haptic1; 0560 strobe + camflash camera package for camflashon)'}, indent=1, sort_keys=True) + '\n')
rt = H / 'payload-final3roundtrip'
for sub, n in (('inst', 'final3'), ('undo', 'final3-undo')):
    (rt / sub).mkdir(parents=True, exist_ok=True)
    if (rt / sub / 'plan.json').exists(): (rt / sub / 'plan.json').unlink()
    os.link(H / f'payload-{n}' / 'plan.json', rt / sub / 'plan.json')
(rt / 'plan.json').write_text(json.dumps({'purpose': 'VM round trip of final3 (rehearsal only)', 'inst': 'payload-final3', 'undo': 'payload-final3-undo'}, indent=1) + '\n')
own = set()
for p in ('haptic-20261114/owned-haptic1.json', 'camflash-20261114/owned-camflashon.json'):
    own |= set(json.loads((BLD / p).read_text()))
need = {'/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches/com.apple.MobileGestalt.plist',
        '/private/var/mobile/Library/Preferences/com.apple.preferences.sounds.plist', '/private/var/mobile/Library/Preferences/com.apple.camera.plist',
        '/private/var/db/nord2-stock', '/private/var/db/nord2-stock/haptic1.json', '/private/var/db/nord2-stock/hapticpref.json', '/private/var/db/nord2-stock/camflashon.json'}
assert need == own, own ^ need
(H / 'owned-final3.json').write_text(json.dumps(sorted(own), indent=0) + '\n')
(H / 'owned-final3-undo.json').write_text(json.dumps(sorted(own), indent=0) + '\n')
(H / 'rehearsal-snapshot.json').write_text(json.dumps({'format': 'nord2-fastroot-1', 'kind': 'snapshot', 'rehearsal_only': True,
    'mirror': str(BLD / 'mirror/rootfs-mirror.img'), 'bytes': 17179869184,
    'root': json.loads((BLD / 'mirror/rootfs-mirror.img.manifest.json').read_text())['root'], 'per_chunk_manifest_matches': True, 'phone_partition_writes': 0}, indent=1) + '\n')
MAN = r'''set +e
mkdir -p /tmp /rt
mount --bind /src /rt || echo 'RT_BIND_FAILED'
phase(){ umount /src 2>/dev/null; mount --bind /rt/$1 /src && echo "RT_PHASE $1"; }
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,plistlib
R='/work/root'; out={}
MGD='/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches'
for top in ['/private/var/db/nord2-stock','/private/var/db/nord2-metal','/System/Library/Extensions/Nord2Metal.bundle',MGD,'/private/var/mobile/Library/Preferences','/private/var/root/Library/Preferences','/System/Library/xpc']:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p) and not os.path.islink(p) and (st.st_size<4<<20): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
c=plistlib.load(open(R+MGD+'/com.apple.MobileGestalt.plist','rb'))['CacheData']
S=[0xa7,0xbd,0x84,0x22e]
out['mg:haptics']=[[c[0x1290+s],c[s*8]] for s in S]; out['mg:camera-flash']=[c[0x1290+0x3f],c[0x3f*8]]
out['mg:others']=hashlib.sha256(bytes(c[i] for i in range(len(c)) if i not in [s*8 for s in S])).hexdigest()
pp=R+'/private/var/mobile/Library/Preferences/com.apple.preferences.sounds.plist'
out['pref:effects-haptic']=repr(plistlib.load(open(pp,'rb')).get('effects-haptic','absent')) if os.path.exists(pp) else 'no file'
cp=R+'/private/var/mobile/Library/Preferences/com.apple.camera.plist'
cd=plistlib.load(open(cp,'rb')) if os.path.exists(cp) else None
out['cam:flash']=repr(cd.get('CAMUserPreferenceDesiredFlashMode','absent')) if cd is not None else 'no file'
out['cam:others']=hashlib.sha256(plistlib.dumps({k:v for k,v in cd.items() if k!='CAMUserPreferenceDesiredFlashMode'},sort_keys=True)).hexdigest() if cd is not None else ''
json.dump(out,open('/tmp/'+sys.argv[1],'w'))
print('MANIFEST',sys.argv[1],len(out),'haptic slots [valid,value]',out['mg:haptics'],'camera-flash',out['mg:camera-flash'],'effects-haptic',out['pref:effects-haptic'],'camera flash mode',out['cam:flash'])
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
for k in ('mg:haptics','mg:camera-flash','pref:effects-haptic','cam:flash'): print('RT_KEY',k,m0[k],'->',m1[k])
print('RT_INSTALL_MG other bytes unchanged', m0['mg:others']==m1['mg:others'], 'camera other keys unchanged', m0['cam:others']==m1['cam:others'])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
i = body('final3', GUESTS['final3'][0], done=False).replace('set +e\n', '', 1); u = body('final3-undo', GUESTS['final3-undo'][0], done=False).replace('set +e\n', '', 1)
(H / 'guest-final3roundtrip.sh').write_text(MAN + 'm m0\nphase inst\n' + i + 'm m1\n' + i + 'm m1b\nphase undo\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
print('generated', sorted(p.name for p in H.glob('guest-*.sh')), 'owned', len(own))
