#!/usr/bin/env python3
"""Generates the guest scripts, payload dirs and owned lists of final-20261114 (run on the host, writes only here).
finalall      = texlayout1 (apps-20261104: Nord2Metal y2s98-texlayout 3ae0c2f8 over gpufinal6, receipt inventory + record texlayout1)
              + dasdmod1   (heat-20261114 'heat1': the stored 1970 lastModulation out of dasd's widget budget preferences)
              + flash1     (bltorch-20261114: MobileGestalt cached camera-flash byte 0 -> 1)
              + bright1    (bltorch-20261114: BKEnableALS false in com.apple.backboardd.plist)
finalall-undo = the same blocks, reverse order, in undo mode.
The block texts are taken verbatim from the three source dirs (texlayout1: the python heredoc of guest-texlayout1[-undo].sh).
Files touched: texlayout1 -> Nord2Metal.bundle/Nord2Metal + /private/var/db/nord2-metal/{receipt.json,Nord2Metal.pre-texlayout1};
dasdmod1/flash1/bright1 -> one preferences/cache file each + their receipt in /private/var/db/nord2-stock. No overlap; none of
them touches /System/Library/xpc/launchd.plist, so the metal receipt's installed_launchd_sha256 stays valid (texlayout1 rewrites
receipt.json but keeps that key).
Chaining: every block's output goes to /tmp/finalall.out; a block runs only if no earlier block printed *_REFUSED or a Traceback
(else FINALALL_SKIPPED); the guest then prints FINALALL_REFUSED and the transaction script commits nothing.
guest-finalallroundtrip.sh = install, install again, undo, undo again with manifests (payload-finalallroundtrip: the install
payload in inst/, the undo payload in undo/, bind-mounted on /src for each phase so the guest bodies are byte-identical)."""
import hashlib, json, os, shutil
from pathlib import Path
H = Path(__file__).resolve().parent; BLD = H.parent
SRC = {'dasdmod1': BLD / 'heat-20261114/block-dasdmod1.py', 'flash1': BLD / 'bltorch-20261114/block-flash1.py',
       'bright1': BLD / 'bltorch-20261114/block-bright1.py'}
def heredoc(p):
    t = p.read_text(); a = t.index("python3 - <<'GUEST'\n") + len("python3 - <<'GUEST'\n"); b = t.index('\nGUEST\n', a)
    assert t.count("<<'GUEST'") == 1; return t[a:b + 1]
blocks = {n: p.read_text() for n, p in SRC.items()}
tex = {False: heredoc(BLD / 'apps-20261104/guest-texlayout1.sh'), True: heredoc(BLD / 'apps-20261104/guest-texlayout1-undo.sh')}
NEW = '3ae0c2f8fcd43a4b59ef0cb014df329f0231d960bbbf732dd03960e576227f3d'; OLD = 'fe406e9c91b42f063235cbac4035977e63bf59012f7c731a0aa4587139435bfe'
sha = lambda b: hashlib.sha256(b).hexdigest()
HEAD = ('set +e\n# %s (generated by final-20261114/make_guests.py; blocks verbatim from heat-20261114, bltorch-20261114, apps-20261104)\n'
        'fsck.hfsplus -f -n /dev/vda | tail -2\nmount -t hfsplus -o rw,force /dev/vda /work/root || exit 1\nmkdir -p /tmp; : > /tmp/finalall.out\n'
        "blk(){ if grep -aq '_REFUSED\\|Traceback' /tmp/finalall.out; then echo \"FINALALL_SKIPPED $1 (an earlier block refused or failed)\"; return 1; fi; echo \"FINALALL_BLOCK $1\"; }\n")
TAIL = ("if grep -aq '_REFUSED\\|Traceback' /tmp/finalall.out; then echo 'FINALALL_REFUSED see the lines above: do not commit'; else echo 'FINALALL_OK %s'; fi\n"
        "echo 'CC_JOB_ADDED %s'\necho 'CC_RECEIPT_UPDATED %s'\nsync\numount /work/root\nfsck.hfsplus -f -n /dev/vda\necho INSTALL_DONE\n")
def body(name, parts, done=True):
    s = HEAD % name
    for b, undo in parts:
        code = tex[undo] if b == 'texlayout1' else 'UNDO=%s\n%s' % (undo, blocks[b])
        s += "blk %s && python3 - <<'GUEST' 2>&1 | tee -a /tmp/finalall.out\n%sGUEST\n" % (b, code)
    t = TAIL % (name, name, 'metal receipt: texlayout1 inventory/record only (launchd.plist untouched)')
    return s + (t if done else t.replace('echo INSTALL_DONE\n', ''))
ORDER = ['texlayout1', 'dasdmod1', 'flash1', 'bright1']
GUESTS = {'finalall': ([(b, False) for b in ORDER], 'texlayout1 + heat1 (dasdmod1) + flash1 + bright1'),
          'finalall-undo': ([(b, True) for b in reversed(ORDER)], 'undo of finalall (reverse order)')}
srcsha = {'heat-20261114/block-dasdmod1.py': sha(blocks['dasdmod1'].encode()), 'bltorch-20261114/block-flash1.py': sha(blocks['flash1'].encode()),
          'bltorch-20261114/block-bright1.py': sha(blocks['bright1'].encode()),
          'apps-20261104/guest-texlayout1.sh': sha((BLD / 'apps-20261104/guest-texlayout1.sh').read_bytes()),
          'apps-20261104/guest-texlayout1-undo.sh': sha((BLD / 'apps-20261104/guest-texlayout1-undo.sh').read_bytes())}
NM = {'finalall': (BLD / 'apps-20261104/payload-texlayout1/Nord2Metal', NEW), 'finalall-undo': (BLD / 'apps-20261104/payload-texlayout1-undo/Nord2Metal', OLD)}
for name, (parts, purpose) in GUESTS.items():
    (H / f'guest-{name}.sh').write_text(body(name, parts))
    d = H / f'payload-{name}'; d.mkdir(exist_ok=True)
    src, want = NM[name]; assert sha(src.read_bytes()) == want
    shutil.copy2(src, d / 'Nord2Metal'); assert sha((d / 'Nord2Metal').read_bytes()) == want
    assert sorted(os.listdir(d)) in (['Nord2Metal'], ['Nord2Metal', 'plan.json']), 'payload dir must hold only Nord2Metal + plan.json (no no-texlayout switch)'
    (d / 'plan.json').write_text(json.dumps({'purpose': purpose, 'guest': f'guest-{name}.sh', 'order': [b for b, _ in parts], 'Nord2Metal_sha256': want,
        'Nord2Metal_role': 'texlayout1 install file (y2s98-texlayout)' if name == 'finalall' else 'texlayout1 undo fallback (gpufinal6), used only if the backup is missing',
        'sources_sha256': srcsha, 'kernel_image': 'q10jcm (0530 clock floor needed by dasdmod1; 0501/0502 by flash1/bright1)'}, indent=1, sort_keys=True) + '\n')
rt = H / 'payload-finalallroundtrip'
for sub, n in (('inst', 'finalall'), ('undo', 'finalall-undo')):
    (rt / sub).mkdir(parents=True, exist_ok=True)
    for f in ('Nord2Metal', 'plan.json'):
        if (rt / sub / f).exists(): (rt / sub / f).unlink()
        os.link(H / f'payload-{n}' / f, rt / sub / f)
(rt / 'plan.json').write_text(json.dumps({'purpose': 'VM round trip of finalall (rehearsal only)', 'inst': 'payload-finalall', 'undo': 'payload-finalall-undo'}, indent=1) + '\n')
# owned lists: the union of the three source lists (texlayout1's is the generic apps list) -- the combination adds no path of its own
own = set()
for p in ('heat-20261114/owned-heat1.json', 'bltorch-20261114/owned-bltorch1.json', 'apps-20261104/owned-texlayout1.json'):
    own |= set(json.loads((BLD / p).read_text()))
need = {'/System/Library/Extensions/Nord2Metal.bundle/Nord2Metal', '/private/var/db/nord2-metal/receipt.json', '/private/var/db/nord2-metal/Nord2Metal.pre-texlayout1',
        '/private/var/mobile/Library/Preferences/com.apple.dasd.widgetRefreshBudgets.plist', '/private/var/db/nord2-stock', '/private/var/db/nord2-stock/dasdmod1.json',
        '/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches/com.apple.MobileGestalt.plist',
        '/private/var/mobile/Library/Preferences/com.apple.backboardd.plist', '/private/var/db/nord2-stock/flash1.json', '/private/var/db/nord2-stock/bright1.json'}
assert need <= own, need - own
(H / 'owned-finalall.json').write_text(json.dumps(sorted(own), indent=0) + '\n')
(H / 'owned-finalall-undo.json').write_text(json.dumps(sorted(own), indent=0) + '\n')   # the undo writes the same paths
(H / 'rehearsal-snapshot.json').write_text(json.dumps({'format': 'nord2-fastroot-1', 'kind': 'snapshot', 'rehearsal_only': True,
    'mirror': str(BLD / 'mirror/rootfs-mirror.img'), 'bytes': 17179869184,
    'root': json.loads((BLD / 'mirror/rootfs-mirror.img.manifest.json').read_text())['root'], 'per_chunk_manifest_matches': True, 'phone_partition_writes': 0}, indent=1) + '\n')
MAN = r'''set +e
mkdir -p /tmp /rt
mount --bind /src /rt || echo 'RT_BIND_FAILED'
phase(){ umount /src 2>/dev/null; mount --bind /rt/$1 /src && echo "RT_PHASE $1 Nord2Metal $(sha256sum /src/Nord2Metal | cut -c1-12)"; }
m(){
mkdir -p /tmp; mount -t hfsplus -o ro,force /dev/vda /work/root && python3 - "$1" <<'PY'
import os,sys,hashlib,json,plistlib
R='/work/root'; out={}
MGD='/private/var/containers/Shared/SystemGroup/systemgroup.com.apple.mobilegestaltcache/Library/Caches'
for top in ['/private/var/db/nord2-stock','/private/var/db/nord2-metal','/System/Library/Extensions/Nord2Metal.bundle',MGD,'/private/var/mobile/Library/Preferences','/private/var/root/Library/Preferences','/System/Library/xpc']:
    for b,ds,fs in os.walk(R+top):
        for n in ['.']+ds+fs:
            p=os.path.normpath(os.path.join(b,n)); st=os.lstat(p)
            out[p[len(R):]]=[st.st_uid,st.st_gid,st.st_mode,st.st_size if not os.path.isdir(p) else 0]
            if os.path.isfile(p) and not os.path.islink(p) and (st.st_size<4<<20): out['sha:'+p[len(R):]]=hashlib.sha256(open(p,'rb').read()).hexdigest()
rc=json.load(open(R+'/private/var/db/nord2-metal/receipt.json'))
out['metal:launchd_ok']=rc.get('installed_launchd_sha256')==hashlib.sha256(open(R+'/System/Library/xpc/launchd.plist','rb').read()).hexdigest()
out['metal:Nord2Metal']=hashlib.sha256(open(R+'/System/Library/Extensions/Nord2Metal.bundle/Nord2Metal','rb').read()).hexdigest()[:12]
out['metal:inventory_ok']=rc['inventory']['System/Library/Extensions/Nord2Metal.bundle']['Nord2Metal'][:12]==out['metal:Nord2Metal']
out['metal:texlayout1']='texlayout1' in rc
c=plistlib.load(open(R+MGD+'/com.apple.MobileGestalt.plist','rb'))['CacheData']; out['mg:camera-flash']=[c[0x1290+0x3f],c[0x3f*8]]
b=plistlib.load(open(R+'/private/var/mobile/Library/Preferences/com.apple.backboardd.plist','rb')); out['bb:BKEnableALS']=repr(b.get('BKEnableALS','absent'))
d=plistlib.load(open(R+'/private/var/mobile/Library/Preferences/com.apple.dasd.widgetRefreshBudgets.plist','rb')); out['dasd:lastModulation']=repr(d.get('lastModulation','absent'))
json.dump(out,open('/tmp/'+sys.argv[1],'w'))
print('MANIFEST',sys.argv[1],len(out),'Nord2Metal',out['metal:Nord2Metal'],'inventory_ok',out['metal:inventory_ok'],'texlayout1 record',out['metal:texlayout1'],'launchd==metal receipt',out['metal:launchd_ok'],
      'lastModulation',out['dasd:lastModulation'],'camera-flash [valid,value]',out['mg:camera-flash'],'BKEnableALS',out['bb:BKEnableALS'])
PY
umount /work/root
}
'''
CMP = r'''python3 - <<'PY'
import json
m0,m1,m1b,m2,m3=[json.load(open('/tmp/'+n)) for n in ('m0','m1','m1b','m2','m3')]
ch=sorted(k for k in set(m0)|set(m1) if m0.get(k)!=m1.get(k))
print('RT_INSTALL_CHANGED', len(ch), ch)
for k in ('metal:Nord2Metal','metal:inventory_ok','metal:texlayout1','metal:launchd_ok','dasd:lastModulation','mg:camera-flash','bb:BKEnableALS'): print('RT_KEY',k,m0[k],'->',m1[k])
print('RT_SECOND_INSTALL_NOOP', m1==m1b)
d=[k for k in set(m0)|set(m2) if m0.get(k)!=m2.get(k)]
print('RT_UNDO_DIFF', len(d), sorted(d)[:20])
print('RT_SECOND_UNDO_NOOP', m2==m3)
PY
echo 'CC_JOB_ADDED rt'; echo 'CC_RECEIPT_UPDATED rt'; echo INSTALL_DONE
'''
i = body('finalall', GUESTS['finalall'][0], done=False).replace('set +e\n', '', 1); u = body('finalall-undo', GUESTS['finalall-undo'][0], done=False).replace('set +e\n', '', 1)
(H / 'guest-finalallroundtrip.sh').write_text(MAN + 'm m0\nphase inst\n' + i + 'm m1\n' + i + 'm m1b\nphase undo\n' + u + 'm m2\n' + u + 'm m3\n' + CMP)
print('generated', sorted(p.name for p in H.glob('guest-*.sh')), 'owned', len(own))
