#!/usr/bin/env python3
"""Step 3 of README-0107-design.md section 12.6, host only.

Reads the vendor MT6893 CPU DVFS tables (work/nord2-current-kernel .../cpufreq_v1/src/mach/mt6893/mtk_cpufreq_opp_pv_table.h, level 1 = FY_30G26G and
CCI_30G26G) and writes nord2_cpuhvfs_tables.h next to this script.  It also reimplements, independently of the C code, what the vendor driver
(cpufreq_v1/src/v2/mtk_cpufreq_hybrid.c: init_cpuhvfs_debug_repo + cpuhvfs_pvt_tbl_create) leaves in the 0x1400-byte CSRAM, starting from a
deterministic "noise" image, and prints the FNV-1a 64 hash of the result: the golden value of nord2_cpuhvfs_init_test.c.

    gen_cpuhvfs_tables.py [--check] [vendor header]      (--check: do not write, exit 1 if the committed header differs from the vendor source)
"""
import re, sys
from pathlib import Path

VENDOR = Path('$HOME/Documents/Codex/2026-10-19/vedi-questa-repo-https-github-com/work/nord2-current-kernel/drivers/misc/mediatek/base/power/cpufreq_v1/src/mach/mt6893/mtk_cpufreq_opp_pv_table.h')
args = [a for a in sys.argv[1:] if a != '--check']
CHECK = '--check' in sys.argv[1:]
src = re.sub(r'/\*.*?\*/', '', Path(args[0] if args else VENDOR).read_text(), flags=re.S)   # the vendor file has a commented-out CCI block

def table(name, cols):
    m = re.search(r'static (?:unsigned int|unsigned char) %s\[[^\]]*\]\[[^\]]*\] = \{(.*?)\n\};' % re.escape(name), src, re.S)
    assert m, name
    rows = [[int(x) for x in r.split(',')] for r in re.findall(r'\{([0-9,\s]+)\}', m.group(1))]
    assert all(len(r) == cols for r in rows), name
    return rows

pvt = table('FY_30G26G', 4)
cci = table('CCI_30G26G', 16)
assert len(pvt) == 64 and len(cci) == 32

# ---- the golden image: vendor semantics in plain python ------------------------------------------------------------------------------------
SIZE = 0x1400
GUARD0, GUARD1 = 0x55aa55aa, 0xaa55aa55
def noise():
    return bytearray(b''.join(((i * 2654435761 + 12345) & 0xffffffff).to_bytes(4, 'little') for i in range(SIZE // 4)))
def w(img, off, v):
    img[off:off + 4] = (v & 0xffffffff).to_bytes(4, 'little')
def image(pin=None):
    img = noise()
    for i, g in enumerate((GUARD0, GUARD1, GUARD0, GUARD1)):          # init_cpuhvfs_debug_repo
        w(img, 4 * i, g)
    for off in range(0x2a0, SIZE, 4):
        w(img, off, 0)
    w(img, 0x2a0, GUARD0)
    for c in range(3):                                                  # the vendor loop stops at the CCI cluster (c != MT_CPU_DVFS_CCI)
        row = (pin[c] if pin else None)
        w(img, 0x320 + 4 * c, (row << 16 | row) if pin else (0 << 16 | 15))
    if pin:                                                             # request words: the rows, and the CCI row from the vendor CCI map [LL row][B row]
        for c in range(3):
            w(img, 0x37c + 4 * c, pin[c])
        w(img, 0x37c + 12, cci[pin[0]][pin[2]])
    for off in range(0x10, 0x250, 4):                                   # cpuhvfs_pvt_tbl_create: memset_io(recordRef, 0, PVT_TBL_SIZE)
        w(img, off, 0)
    def ref(k, v): w(img, 0x10 + 4 * k, v)
    for i in range(16):
        for c, cmask in ((0, 0xff), (1, 0xff), (2, 0xfff), (3, 0xff)):
            r = pvt[16 * c + i]
            ref(36 * c + i, ((r[1] & 0xfff) << 16) | (r[0] & 0xffff))
            ref(36 * c + 16 + i, ((r[3] & cmask) << 16) | (r[2] & 0xff))
    for c in range(4):
        ref(36 * c + 32, 0xffffffff)
    for off in range(0xfa0, 0xfa0 + 0x1fc):                             # CCI map: memset_io of PVT_CCI_TBL_SIZE = 0x1fc bytes ...
        img[off] = 0
    for i in range(32):                                                 # ... then 32 x 16 bytes (512) are stored
        for j in range(16):
            img[0xfa0 + 16 * i + j] = cci[i][j]
    return img
def fnv64(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h

out = ['/* GENERATED by gen_cpuhvfs_tables.py from the vendor mt6893 mtk_cpufreq_opp_pv_table.h (level 1: FY_30G26G, CCI_30G26G). Do not edit. */',
       '#ifndef NORD2_CPUHVFS_TABLES_H', '#define NORD2_CPUHVFS_TABLES_H', '#include <stdint.h>', '',
       '/* rows: {MHz, Vproc in 6.25 mV PMIC steps, post_div, clk_div}; LL rows 0..15, L 16..31, B 32..47, CCI 48..63 */',
       'static const uint16_t n2dv_l1_pvt[64][4] = {']
for r in pvt:
    out.append('\t{ %d, %d, %d, %d },' % tuple(r))
out += ['};', '', '/* CCI frequency map: 32 rows x 16 bytes (two 16 x 16 halves) */', 'static const uint8_t n2dv_l1_cci[32][16] = {']
for r in cci:
    out.append('\t{ ' + ', '.join(str(x) for x in r) + ' },')
img0, img1 = image(), image((1, 14, 15))
out += ['};', '',
        '/* golden: FNV-1a 64 of the 0x1400-byte CSRAM after the init plan, starting from the test\'s noise image (i * 2654435761 + 12345) */',
        '#define N2DV_GOLDEN_FNV64_DEFAULT 0x%016xull' % fnv64(img0),
        '#define N2DV_GOLDEN_FNV64_PINNED_1_14_15 0x%016xull' % fnv64(img1), '#endif', '']
target = Path(__file__).parent / 'nord2_cpuhvfs_tables.h'
text = '\n'.join(out)
if CHECK:
    if target.read_text() != text:
        print('nord2_cpuhvfs_tables.h differs from the vendor tables'); sys.exit(1)
    print('nord2_cpuhvfs_tables.h matches the vendor tables'); sys.exit(0)
target.write_text(text)
print('rows', len(pvt), len(cci), 'default', hex(fnv64(img0)), 'pinned', hex(fnv64(img1)))
