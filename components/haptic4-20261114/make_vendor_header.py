#!/usr/bin/env python3
"""make_vendor_header.py -- 0611 vendor mode: Android's aw8697_haptic_170.bin (odm partition, /odm/firmware or /vendor/firmware)
-> bsd/dev/nord2_haptic_vendor.h (compiled with -DN2H_VENDOR_RAM / the 0612 patch).

File format [aw8697.c aw8697_ram_loaded + aw8697_container_update]: bytes 0..1 = big-endian checksum of bytes 2..end (16-bit sum),
bytes 2..3 = SRAM base address, bytes 4.. = what is written from the base: version byte, 4-byte entries {start H,L, end H,L}
(absolute, ram_num = (first start - base - 1) / 4), then signed 8-bit samples at 24 kHz.

usage: make_vendor_header.py BIN OUT_H [--tick N] [--click N] [--heavy N] [--list]
Without --tick/--click/--heavy the indices are chosen from the analysis (printed): tick = the shortest waveform of 5..30 ms with a
peak >= 48, click = the strongest of 10..32 ms (closest to 20 ms on ties), heavy = the most energetic of 18..50 ms.
"""
import argparse, hashlib, math, sys


def parse(data):
    if len(data) < 16:
        raise SystemExit("file too short")
    ck = (data[0] << 8) | data[1]
    s = sum(data[2:]) & 0xFFFF
    if s != ck:
        raise SystemExit(f"checksum mismatch: file says {ck:#06x}, sum is {s:#06x} (not an AW8697 RAM file?)")
    base = (data[2] << 8) | data[3]
    img = bytes(data[4:])
    if base == 0 or base + len(img) > 0x2000:
        raise SystemExit(f"base {base:#06x} + {len(img)} bytes does not fit the 8 KiB SRAM")
    first = (img[1] << 8) | img[2]
    n = (first - base - 1) // 4
    if n < 1 or n > 127 or 1 + 4 * n > len(img):
        raise SystemExit(f"implausible waveform count {n} (first start {first:#06x})")
    waves = []
    for k in range(1, n + 1):
        e = img[1 + 4 * (k - 1): 5 + 4 * (k - 1)]
        st, en = (e[0] << 8) | e[1], (e[2] << 8) | e[3]
        if not (base < st <= en < base + len(img)):
            raise SystemExit(f"waveform {k}: {st:#06x}..{en:#06x} outside the image")
        smp = [b - 256 if b > 127 else b for b in img[st - base: en - base + 1]]
        peak = max(abs(v) for v in smp)
        energy = sum(v * v for v in smp)
        zc, last = 0, 0
        for v in smp:
            sg = 1 if v > 8 else -1 if v < -8 else 0
            if sg:
                if last and sg != last:
                    zc += 1
                last = sg
        ms = len(smp) * 1000.0 / 24000.0
        hz = zc / 2.0 / (len(smp) / 24000.0) if smp else 0
        waves.append(dict(k=k, start=st, end=en, n=len(smp), ms=ms, peak=peak, energy=energy, zc=zc, hz=hz))
    return ck, base, img, n, waves


def choose(waves, lo, hi, key):
    c = [w for w in waves if lo <= w["ms"] <= hi and w["peak"] >= 48]
    return min(c, key=key)["k"] if c else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bin"); ap.add_argument("out")
    ap.add_argument("--tick", type=int); ap.add_argument("--click", type=int); ap.add_argument("--heavy", type=int)
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    data = open(a.bin, "rb").read()
    ck, base, img, n, waves = parse(data)
    print(f"file {a.bin}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()[:16]}, checksum {ck:#06x} OK, base {base:#06x}, "
          f"image {len(img)} bytes, version {img[0]:#04x}, {n} waveforms")
    for w in waves:
        print(f"  wave {w['k']:3d}: {w['start']:#06x}..{w['end']:#06x} {w['n']:5d} samples {w['ms']:7.1f} ms peak {w['peak']:3d} "
              f"rms {math.sqrt(w['energy'] / max(1, w['n'])):5.1f} ~{w['hz']:5.0f} Hz ({w['zc']} crossings)")
    if a.list:
        return
    tick = a.tick or choose(waves, 5, 30, lambda w: (w["ms"], -w["peak"]))
    click = a.click or choose(waves, 10, 32, lambda w: (-w["peak"], abs(w["ms"] - 20)))
    heavy = a.heavy or choose(waves, 18, 50, lambda w: (-w["energy"], w["ms"]))
    for name, v in (("tick", tick), ("click", click), ("heavy", heavy)):
        if not v or not 1 <= v <= n:
            raise SystemExit(f"no {name} waveform chosen; pass --{name} N (see the list above)")
    print(f"chosen: tick = wave {tick} ({waves[tick-1]['ms']:.1f} ms), click = wave {click} ({waves[click-1]['ms']:.1f} ms), "
          f"heavy = wave {heavy} ({waves[heavy-1]['ms']:.1f} ms)")
    rows = []
    for i in range(0, len(img), 24):
        rows.append("\t" + ", ".join(f"0x{b:02x}" for b in img[i:i + 24]) + ",")
    out = f"""/*
 * nord2_haptic_vendor.h -- generated by haptic2-20261114/make_vendor_header.py (0611 vendor mode, -DN2H_VENDOR_RAM).
 * Source: Android's AW8697 RAM file ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}, checksum {ck:#06x}),
 * base {base:#06x}, {n} waveforms.  tick = {tick}, click = {click}, heavy = {heavy}.
 */
#ifndef NORD2_HAPTIC_VENDOR_H
#define NORD2_HAPTIC_VENDOR_H
#define N2H_VENDOR_BASE         {base:#06x}u
#define N2H_VENDOR_LEN          {len(img)}u
#define N2H_VENDOR_NWAVES       {n}u
static const uint8_t n2h_vendor_idx[4] = {{ 0, {tick}, {click}, {heavy} }};
static const uint8_t n2h_vendor_img[N2H_VENDOR_LEN] = {{
{chr(10).join(rows)}
}};
#endif /* NORD2_HAPTIC_VENDOR_H */
"""
    open(a.out, "w").write(out)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
