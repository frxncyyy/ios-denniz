#!/usr/bin/env python3
"""Regenerate the embedded D8F18H-linear1 TGP2 fixture and its provenance.

The input is the lowering evidence produced with compiler 742cdf3d:
  gpu/build/lowering-claude-20261025/d8f-spot/wls-on/D8F18H-linear1/compute.spv
The compiler entry point is called with specialization ID 0 as a 4-byte bool
value 1 (the declared SPIR-V specialization type is 32-bit, not 1 byte).
The resulting packet must match the lowering evidence SHA-256 in v2.log.

This is a host-only, single compile.  The test suite embeds the generated bytes
in d8f18h_pkg.h and independently parses the packet header in C.
"""
from __future__ import annotations

import ctypes
import hashlib
import json
import os
from pathlib import Path

EXPECTED_PACKAGE = "a179cc460ca457174dbb72ac6f6e29c474470b486331eaef77a38e18b8d2d6df"
EXPECTED_SPV = "791bd8cc02a404ab7a362ec753e5e5ff54dc0677e6c65a44da5a562d2720a899"
EXPECTED_COMPILER = "742cdf3d8d10364402ff3f1c7896be43a884e93f95684edf891b206db1c7ffbb"
EXPECTED_HEADER_SHA = "8d55e0a6a33543f2d71a6afb199efac795ff2d3b0fde7c989af78e405410e901"
TLS_BYTES = 32
PACKAGE_SIZE = 9920

HERE = Path(__file__).resolve().parent
GPU = HERE.parents[3]


class _Spec(ctypes.Structure):
    _fields_ = [("id", ctypes.c_uint32), ("size", ctypes.c_uint32),
                ("data", ctypes.c_ubyte * 8)]


class _Blob(ctypes.Structure):
    _fields_ = [("data", ctypes.c_void_p), ("size", ctypes.c_size_t)]


def compile_packet(spv: bytes) -> bytes:
    lib_path = GPU / "build/mesa-build/src/panfrost/clc/libnord2_mali_runtime.so"
    if hashlib.sha256(lib_path.read_bytes()).hexdigest() != EXPECTED_COMPILER:
        raise SystemExit(f"compiler changed from 742cdf3d: {lib_path}")
    lib = ctypes.CDLL(str(lib_path))
    fn = lib.tegu_mali_compile_compute_v2
    fn.restype = ctypes.c_int
    fn.argtypes = [ctypes.c_void_p, ctypes.c_size_t,
                   ctypes.POINTER(_Spec), ctypes.c_size_t,
                   ctypes.POINTER(_Blob), ctypes.c_char_p, ctypes.c_size_t]
    free = lib.tegu_mali_free
    free.argtypes = [ctypes.POINTER(_Blob)]
    spec = _Spec(id=0, size=4)
    spec.data[0] = 1
    err = ctypes.create_string_buffer(1024)
    out = _Blob()
    rc = fn(spv, len(spv), ctypes.byref(spec), 1, ctypes.byref(out), err, 1024)
    if rc:
        raise SystemExit(f"compile failed rc={rc}: {err.value!r}")
    try:
        return ctypes.string_at(out.data, out.size)
    finally:
        free(ctypes.byref(out))


def header_bytes(package: bytes) -> str:
    lines = [
        "/* Generated by regenerate_d8f18h_packet.py; real TGP2 packet from",
        " * lowering final-742cdf3d D8F18H-linear1 compute.spv; TLS 32. */",
        "static const unsigned char d8f18h_pkg[] = {",
    ]
    for i in range(0, len(package), 12):
        lines.append("    " + ",".join(str(x) for x in package[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    spv_path = Path(os.environ.get(
        "D8F18H_SPV",
        GPU / "build/lowering-claude-20261025/d8f-spot/wls-on/"
              "D8F18H-linear1/compute.spv",
    ))
    spv = spv_path.read_bytes()
    if hashlib.sha256(spv).hexdigest() != EXPECTED_SPV:
        raise SystemExit(f"SPIR-V changed: {spv_path}")
    package = compile_packet(spv)
    digest = hashlib.sha256(package).hexdigest()
    if digest != EXPECTED_PACKAGE:
        raise SystemExit(f"packet changed: {digest}")
    if len(package) != PACKAGE_SIZE:
        raise SystemExit(f"packet size {len(package)}")
    header = header_bytes(package)
    header_sha = hashlib.sha256(header.encode()).hexdigest()
    (HERE / "d8f18h_pkg.h").write_text(header)
    meta = {
        "source": str(spv_path.relative_to(GPU)),
        "spv_sha256": EXPECTED_SPV,
        "compiler_sha256": EXPECTED_COMPILER,
        "specialization": [{"id": 0, "size": 4, "value": 1}],
        "package_sha256": digest,
        "package_size": len(package),
        "tls_bytes": TLS_BYTES,
        "wls_bytes": 0,
        "header_sha256": header_sha,
        "expected_header_sha256": EXPECTED_HEADER_SHA,
        "header_matches_recorded": header_sha == EXPECTED_HEADER_SHA,
    }
    (HERE / "d8f18h_pkg.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(json.dumps(meta, indent=2))
    return 0 if header_sha == EXPECTED_HEADER_SHA else 1


if __name__ == "__main__":
    raise SystemExit(main())
