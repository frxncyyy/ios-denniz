#!/usr/bin/env python3
"""Regenerate gpu/build/texture-coverage-20261026/MATRIX.md from measured inputs:
ios16_pixel_formats.json (SDK enum), translator-format-audit.jsonl (Rust
vk_format under the shipped native profile), n2t-formats.txt (n2t_format_query
dump) and the frontend/planner admission sets, which are re-verified against
the source text so the table cannot silently drift."""
import json, re
from pathlib import Path
D = Path(__file__).resolve().parents[1]
G = D.parents[1]
enc = (G / 'metal/tegu/render_encoder.inc').read_text()
rust = (G / 'metal/tegu/air_bridge.rs').read_text()
# Frontend sampled bind set (tegu_generic_texture_ok -> tegu_texture_sampled_format
# = n2t minus depth) and planner set (n2t_sampled_format, checked equal to n2t by
# tests/texture_format_frontend_test.py).
assert 'tegu_texture_sampled_format(t->format)' in enc and 'n2t_sampled_format(r.format)' in rust
import subprocess as _sp
_out = D / 'host/n2t_dump'
FRONT = PLAN = {int(x) for x in _sp.run([str(_out)], check=True, stdout=_sp.PIPE).stdout.split()}
OUTCOMES = {int(k): v for k, v in json.load(open(D / 'host/format-draw-outcomes.json')).items()}
INTEGER = {13, 14, 23, 24, 33, 34, 53, 54, 63, 64, 73, 74, 91, 103, 104, 113, 114, 123, 124}
# Colour targets: air_bridge.rs n2r_target_format (blendable tile formats, then
# the raw opaque-only ones), mirrored by nord2_metal_render.h n2r_rt_is_raw.
_m = re.search(r'fn n2r_target_format\(format:u32\)->bool \{\n matches!\(format,([^)]*)\)', rust)
assert _m, 'n2r_target_format moved'
_codes = [int(x) for x in re.sub(r'\s', '', _m.group(1)).split('|')]
RT_BLEND = set(_codes[:_codes.index(12)])
RT_RAW = set(_codes[_codes.index(12):])
RT = RT_BLEND | RT_RAW
assert 'if !n2r_target_format(format)||count==4' in rust
DEPTH_SAMPLED = {250, 252}
assert 'matches!(r.format,250|252)' in rust
ASTC = set(range(186, 201)) | set(range(204, 219))
ASTC -= {191, 209}
XR_SHADOW = {552, 553, 554, 555}
ios = json.load(open(D / 'ios16_pixel_formats.json'))
audit = {json.loads(l)['raw']: json.loads(l) for l in open(D / 'translator-format-audit-p2.jsonl')}
n2t = {}
for line in open(D / 'n2t-formats.txt'):
    f = line.split(); n2t[int(f[0])] = f
def tr(r, k):
    x = r[k]
    if x['ok']:
        e = x['emulation']
        return 'ok' if e == 'Direct' else ('ok(swz)' if e == 'SwizzledView' else e)
    w = x['why']
    if 'NotImplemented' in w or 'not_implemented' in w: return 'NI'
    if 'PixelFormatUsage' in w: return 'n/a'
    return 'profile'
rows = []
for raw, name, unavailable in ios:
    if raw == 0: continue
    r = audit.get(raw)
    t = {k: tr(r, k) for k in ('sample', 'sample_linear', 'render', 'render_blend', 'storage')} if r else {}
    native = raw in n2t
    o = OUTCOMES.get(raw)
    drawn = o and o[1] == '0' and o[2] == '4'
    if unavailable:
        status = 'N/A on iOS (API_UNAVAILABLE)'
    elif raw in FRONT and drawn:
        how = ('sRGB raw-view translator variant' if raw in (11, 31, 71, 81) else
               'integer class; float slot via cross-class variant' if o and raw in INTEGER else 'native')
        rt = ('RT native (blend)' if raw in RT_BLEND else 'RT native opaque-only (raw)' if raw in RT_RAW else 'RT refused')
        status = f'SAMPLE {how}, host draw status 4 (2D; mips/arrays/3D/cube on the specialized path); {rt}'
    elif raw in DEPTH_SAMPLED:
        status = 'SAMPLE native on the specialized path (depth2d sample (d,d,d,1) + sample_compare, DEPTH_SAMPLING); attachment store refused'
    elif raw in XR_SHADOW:
        status = 'EMULATED: RGBA16F internal (IOSurface decode/encode shadows, private XR textures, XR pipelines compile RGBA16F); blending fp16 approx'
    elif 130 <= raw <= 153:
        status = 'REFUSED: BC is not an iPhone GPU family feature (supportsBCTextureCompression=NO); no Mali evidence'
    elif 160 <= raw <= 167:
        status = 'REFUSED: Mali has no PVRTC; translator NI/profile; planned CPU decode to RGBA8 on upload'
    elif raw in (240, 241):
        status = 'REFUSED: translator NI; Mali YUYV8 exists; planned CPU decode/native YUYV'
    elif 500 <= raw <= 545:
        status = 'EMULATED: IOSurface YCbCr decode shadow (Metal integer model, bit-exact test)'
    elif raw >= 250:
        status = 'REFUSED for sampling: depth/stencil execution not in generic path' + ('' if native else '; no n2t mapping')
    elif raw == 41:
        status = 'REFUSED: Mali A1_BGR5_UNORM (66) exists but Mesa never maps it (no independent check); planned rotated layout + CPU conversion'
    elif native:
        status = 'REFUSED by frontend/planner gate only (n2t native, translator ok) -> next: P2 broadening'
    else:
        status = 'REFUSED: no n2t mapping'
    rows.append((raw, name, 'yes' if native else '-', t, status))
out = ['# Texture / pixel-format coverage matrix (iOS 16.5 SDK MTLPixelFormat)', '',
       'Generated by tools/make_matrix.py from measured inputs; regenerate after source changes.',
       'Columns: n2t = Mali arch9 descriptor mapping exists (nord2_texture_resources.h);',
       'translator = metal2vulkan vk_format under the shipped native profile (sample / linear filter / render / blend / storage):',
       '`ok` direct, `ok(swz)` swizzled view, emulation name, `profile` = profile lacks the Vulkan format/feature, `NI` = not implemented, `n/a` = invalid usage.',
       'Status is the end-to-end frontend result today. Host tests only; no device claim.', '',
       '| fmt | name | n2t | sample | linear | render | blend | storage | status |', '|---|---|---|---|---|---|---|---|---|']
for raw, name, native, t, status in rows:
    out.append(f"| {raw} | {name} | {native} | {t.get('sample','')} | {t.get('sample_linear','')} | {t.get('render','')} | {t.get('render_blend','')} | {t.get('storage','')} | {status} |")
(D / 'MATRIX.md').write_text('\n'.join(out) + '\n' + (D / 'tools/matrix_tail.md').read_text())
print('rows', len(rows))
