#!/usr/bin/env python3
"""Markdown appendix from inventory.json (IMPL / REFUSE / MISSING per MTL protocol, missing selectors listed)."""
import json
r=json.load(open('inventory.json'))
out=['## Appendix: per-protocol coverage (iPhoneOS 16.5 SDK headers vs frontend; generated by gen_table.py)\n',
     '| protocol | Tegu class | IMPL | REFUSE | MISSING | total |','|---|---|---|---|---|---|']
miss_lines=[]
ti=tr=tm=0
for n,v in r.items():
    rows=v['rows']
    i=sum(x['status']=='IMPL' for x in rows);rf=sum(x['status']=='REFUSE' for x in rows);m=sum(x['status']=='MISSING' for x in rows)
    ti+=i;tr+=rf;tm+=m
    out.append(f"| {n} | {', '.join(v['classes']) or '-'} | {i} | {rf} | {m} | {len(rows)} |")
    if m: miss_lines.append(f"* **{n}**: "+' '.join(x['selector'] for x in rows if x['status']=='MISSING'))
out.append(f"| **total** | | **{ti}** | **{tr}** | **{tm}** | **{ti+tr+tm}** |\n")
out.append('Missing selectors (a call is an unrecognized-selector process death; all belong to features the device does not advertise, to base-class capability getters, or to owners named above):\n')
out+=miss_lines
print('\n'.join(out))
