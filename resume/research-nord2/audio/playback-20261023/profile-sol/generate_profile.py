#!/usr/bin/env python3
"""Generate immutable sourced table; rejects foreign container and dangerous writes."""
from parse_container import Container, Invalid
from pathlib import Path
import json
SHA='635300fbc96f258ff9a35f82435f2e9d3ff6f1370c156067b40146e011038692'
d=Container(Path('tfa98xx.cnt').read_bytes()).decode()
assert d['sha256']==SHA and [v['address'] for v in d['devices']]==[0x34,0x37]
lines=['/* Generated by generate_profile.py; private sourced evidence, no OTP/MTP writes. */','#ifndef NORD2_SOURCED_PROFILE_H','#define NORD2_SOURCED_PROFILE_H','#include <stdint.h>','struct nsp_op { uint8_t reg; uint16_t mask, value; uint32_t delay_us; };', '#define NSP_SILICON_MASK 0x00ffu','#define NSP_SILICON_VALUE 0x0074u', '#define NSP_SAMPLE_RATE 48000u', '#define NSP_SHA256 "'+SHA+'"']
for i,v in enumerate(d['devices']):
 p=[p for p in v['profiles'] if p['name']=='speaker'];assert len(p)==1
 ops=v['device_ops']+p[0]['ops']
 # Keys were already performed by exact silicon init; never replay constant unlock.
 ops=[o for o in ops if 'reg' in o and o['reg'] not in (0x0f,0xa0,0xa1)]
 # No MTP/OTP data or command register permitted. Volatile analog/timing only.
 allow={0,2,0x20,0x21,0x22,0x23,0x26,0x27,0x51,0x52,0x53,0x56,0x58,0x61,0x62,0x64,0x68,0x6f,0x70,0x74,0x75,0x76,0x80,0x83,0x84,0x85,0x88,0xb0,0xc4}
 assert len(ops)==52 and all(o['reg'] in allow for o in ops)
 lines+=['static const struct nsp_op nsp_amp%d[] = {'%i]+[' {0x%02x,0x%04x,0x%04x,%du}, /* container offset %u */'%(o['reg'],o['mask'],o['value'],o['delay_us'],o['offset']) for o in ops]+['};']
lines+=['#endif']
Path('sourced_profile.h').write_text('\n'.join(lines)+'\n')
print('generated2x52 operations; 3volatile unlock descriptors omitted peramp;2non-register markers omitted peramp')
